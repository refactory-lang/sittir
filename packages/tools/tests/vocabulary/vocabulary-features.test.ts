import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { drift, generate, vocabularyFeatureIssues } from '../../src/vocabulary/index.ts';
import { type Plan, plan } from '../../src/vocabulary/plan.ts';
import { type VocabularySource, readVocabularySource } from '@sittir/codegen/bindings';
import { augmentation, featuresIndex } from '../../src/vocabulary/write.ts';

const HEADER = '// Generated by `sittir tool vocabulary-features --write` from the feature folders: do not edit.';
const STALE = 'not what the feature folders generate; run sittir tool vocabulary-features --write';

const dirs: string[] = [];
afterAll(() => {
	for (const dir of dirs) rmSync(dir, { recursive: true, force: true });
});

function vocabulary(files: Readonly<Record<string, string>>): string {
	const dir = mkdtempSync(join(tmpdir(), 'vocabulary-features-'));
	dirs.push(dir);
	for (const [file, text] of Object.entries(files)) {
		mkdirSync(dirname(join(dir, file)), { recursive: true });
		writeFileSync(join(dir, file), text);
	}
	return dir;
}

function feature(dir: string, marker: string, stubs: Readonly<Record<string, string>>): Record<string, string> {
	const exports = Object.keys(stubs).map((file) => `export type * from './${file}';`);
	return {
		[`features/${dir}/index.ts`]: `${[...exports, marker].join('\n')}\n`,
		...Object.fromEntries(Object.entries(stubs).map(([file, text]) => [`features/${dir}/${file}`, text]))
	};
}

const DECLARATION = `export interface Declaration<G extends GrammarContext<G>> {
	readonly $kind: 'declaration';
	readonly name: G['identifier'];
}
export namespace Declaration {
	export interface Function<G extends GrammarContext<G>> extends SubKindOf<V.Declaration<G>> {
		readonly $kind: 'declaration.function';
		readonly parameters: readonly unknown[];
	}
}
`;

const ASYNC_AWAIT = feature('async-await', 'export interface AsyncAwait {\n\treadonly asyncAwait: true;\n}', {
	'declaration.ts': `export namespace Declaration {
	export interface Function<G extends GrammarContext<G>> {
		readonly async?: Flag;
	}
}
`
});

const METHODS = feature('methods', 'export interface Methods {\n\treadonly methods: true;\n}', {
	'declaration.ts': `export namespace Declaration {
	export interface Method<G extends GrammarContext<G>> extends SubKindOf<V.Declaration<G>> {
		readonly $kind: 'declaration.method';
		readonly static?: Flag;
	}
	export namespace Method {
		export interface Getter<G extends GrammarContext<G>> extends SubKindOf<V.Declaration.Method<G>> {
			readonly $kind: 'declaration.method.getter';
		}
	}
}
`
});

const ACCESSORS = feature('methods/accessors', 'export interface Accessors extends Methods {\n\treadonly accessors: true;\n}', {
	'declaration.ts': `export namespace Declaration {
	export interface Method<G extends GrammarContext<G>> {
		readonly accessor?: 'get' | 'set';
	}
	export namespace Method {
		export interface Getter<G extends GrammarContext<G>> {
			readonly accessor: 'get';
		}
	}
}
`
});

const CLEAN = { 'declaration.ts': DECLARATION, ...ASYNC_AWAIT, ...METHODS, ...ACCESSORS };

const MACROS = feature('macros', 'export interface Macros {\n\treadonly macros: true;\n}', {
	'macro.ts': `export namespace Macro {
	export interface Rule<G extends GrammarContext<G>> {
		readonly $kind: 'macro.rule';
	}
}
`
});

const issues = async (files: Readonly<Record<string, string>>): Promise<readonly string[]> => plan(await readVocabularySource(vocabulary(files))).issues;

describe('the vocabulary', () => {
	it('has no feature issues, and its generated files are what its feature folders generate', async () => {
		expect(await vocabularyFeatureIssues()).toEqual([]);
	}, 60_000);

});

describe('plan', () => {
	let p: Plan;
	beforeAll(async () => {
		p = plan(await readVocabularySource(vocabulary(CLEAN)));
	});

	it('finds nothing wrong with a well-formed feature tree', async () => {
		expect([...p.issues, ...p.notes]).toEqual([]);
	});

	it('gives each kind a feature adds to that feature', async () => {
		expect(Object.fromEntries([...p.kinds].map(([path, k]) => [path, k.feature?.name]))).toEqual({
			declaration: undefined,
			'declaration.function': undefined,
			'declaration.method': 'Methods',
			'declaration.method.getter': 'Methods'
		});
	});

	it('gates a member a stub adds to a kind it does not declare, and leaves a kind’s own members to the kind', async () => {
		expect(Object.fromEntries([...p.owned].map(([path, members]) => [path, Object.fromEntries([...members].map(([name, o]) => [name, o.feature.name]))]))).toEqual({
			'declaration.function': { async: 'AsyncAwait' },
			'declaration.method': { accessor: 'Accessors' },
			'declaration.method.getter': { accessor: 'Accessors' }
		});
	});

	it('makes every proper prefix of a kind a level holding each kind at or under it', async () => {
		expect(Object.fromEntries(p.levels)).toEqual({
			Declaration: ['Declaration', 'Declaration.Function', 'Declaration.Method', 'Declaration.Method.Getter'],
			'Declaration.Method': ['Declaration.Method', 'Declaration.Method.Getter']
		});
	});

	it('reports a member two features own', async () => {
		const properties = feature('properties', 'export interface Properties {\n\treadonly properties: true;\n}', {
			'declaration.ts': `export namespace Declaration {
	export interface Method<G extends GrammarContext<G>> {
		readonly accessor?: boolean;
	}
}
`
		});
		expect(await issues({ ...CLEAN, ...properties })).toEqual(['declaration.method.accessor: owned by Accessors and Properties']);
	});

	it('reports members added to a kind the vocabulary does not declare', async () => {
		const lambda = feature('async-await', 'export interface AsyncAwait {\n\treadonly asyncAwait: true;\n}', {
			'declaration.ts': `export namespace Declaration {
	export interface Lambda<G extends GrammarContext<G>> {
		readonly async?: Flag;
	}
}
`
		});
		expect(await issues({ ...CLEAN, ...lambda })).toEqual(['AsyncAwait: Declaration.Lambda adds members to a kind the vocabulary does not declare']);
	});

	it('lets a feature require a member only when it extends the feature that owns it', async () => {
		const generators = (marker: string): Record<string, string> =>
			feature('generators', marker, {
				'declaration.ts': `export namespace Declaration {
	export interface Function<G extends GrammarContext<G>> {
		readonly async: Flag;
	}
}
`
			});
		expect(await issues({ ...CLEAN, ...generators('export interface Generators {\n\treadonly generators: true;\n}') })).toEqual([
			'Generators restates declaration.function.async, which AsyncAwait owns, and does not extend AsyncAwait'
		]);
		expect(await issues({ ...CLEAN, ...generators('export interface Generators extends AsyncAwait {\n\treadonly generators: true;\n}') })).toEqual([]);
	});

	it('reports a member typed by a direct reference to a kind a feature restates, or to a level holding one', async () => {
		const field = DECLARATION.replace(
			'\t}\n}\n',
			`\t}
	export interface Field<G extends GrammarContext<G>> extends SubKindOf<V.Declaration<G>> {
		readonly $kind: 'declaration.field';
		readonly type?: G['slots']['declaration.field']['type'];
	}
	export interface Union<G extends GrammarContext<G>> extends SubKindOf<V.Declaration<G>> {
		readonly $kind: 'declaration.union';
		readonly body: V.Declaration.Field<G>[];
		readonly fields: G['slots']['declaration.union']['fields'][];
		readonly members: V.Declaration.Any<G>[];
	}
}
`
		);
		const typing = feature('manifest-typing', 'export interface ManifestTyping {\n\treadonly manifestTyping: true;\n}', {
			'declaration.ts': `export namespace Declaration {
	export interface Field<G extends GrammarContext<G>> {
		readonly type: G['slots']['declaration.field']['type'];
	}
}
`
		});
		expect(await issues({ ...CLEAN, 'declaration.ts': field, ...typing })).toEqual([
			'declaration.union.body references V.Declaration.Field, and ManifestTyping restates declaration.field: type it through the slot table',
			'declaration.union.members references V.Declaration.Any, and ManifestTyping restates declaration.field: type it through the slot table'
		]);
	});

	it('reports a base declaration of a member a feature gates on the same line', async () => {
		const arrow = DECLARATION.replace(
			'\t}\n}\n',
			`\t}
	export namespace Function {
		export interface Arrow<G extends GrammarContext<G>> extends SubKindOf<V.Declaration.Function<G>> {
			readonly $kind: 'declaration.function.arrow';
			readonly async?: Flag;
		}
	}
}
`
		);
		const p = plan(await readVocabularySource(vocabulary({ ...CLEAN, 'declaration.ts': arrow })));
		expect(p.issues).toEqual(['AsyncAwait owns async at declaration.function, and the kind declares it at declaration.function.arrow, which inherits it']);
		expect(p.notes).toEqual(['async is gated at some kinds and stays in the base at 1: declaration.function.arrow']);
	});

	it('reports a feature whose folder sits in another feature’s folder without extending it', async () => {
		const getters = feature('methods/getters', 'export interface Getters {\n\treadonly getters: true;\n}', {});
		expect(await issues({ ...CLEAN, ...getters })).toEqual(['Getters sits in features/methods but does not extend Methods']);
	});

	it('reports a qualified name two declarations give different paths', async () => {
		const lambdas = feature('lambdas', 'export interface Lambdas {\n\treadonly lambdas: true;\n}', {
			'declaration.ts': `export namespace Declaration {
	export interface Function<G extends GrammarContext<G>> extends SubKindOf<V.Declaration<G>> {
		readonly $kind: 'declaration.lambda';
	}
}
`
		});
		expect(await issues({ ...CLEAN, ...lambdas })).toEqual([
			'Declaration.Function: the base gives it the path declaration.function, and Lambdas gives it declaration.lambda'
		]);
	});

	it('reports a kind refined by a value that is not a kind', async () => {
		const refined = DECLARATION.replace(
			'\t}\n}\n',
			`\t}
	export interface Public<G extends GrammarContext<G>> extends RefinedBy<V.Declaration<G>, V.Declaration.Function.Any<G>> {
		readonly $kind: 'declaration.public';
	}
}
`
		);
		expect(await issues({ ...CLEAN, 'declaration.ts': refined })).toEqual(['declaration.public is refined by Declaration.Function.Any, which is not a kind']);
	});

	it('reports a path segment that is also a flag of the path before it', async () => {
		const statics = feature('methods/statics', 'export interface Statics extends Methods {\n\treadonly statics: true;\n}', {
			'declaration.ts': `export namespace Declaration {
	export namespace Method {
		export interface Static<G extends GrammarContext<G>> extends SubKindOf<V.Declaration.Method<G>> {
			readonly $kind: 'declaration.method.static';
		}
	}
}
`
		});
		expect(await issues({ ...CLEAN, ...statics })).toEqual(['declaration.method.static: static is a flag of declaration.method']);
	});

	it('reports a kind in a namespace no base file declares', async () => {
		expect(await issues({ ...CLEAN, ...MACROS })).toEqual(['macro.rule: Macros declares it in Macro, a namespace no base file declares']);
	});
});

describe('the synonym collision rule', () => {
	const synonyms = (levels: string, flags = ''): Promise<readonly string[]> =>
		issues({
			...CLEAN,
			'declaration.ts': `${DECLARATION}export interface DeclarationSynonyms {\n${levels}}\n`,
			'utils.ts': `export interface FlagSynonyms {\n${flags}}\n`
		});

	it('passes tables whose every synonym spells one name at each position it has', async () => {
		expect(await synonyms("\treadonly function: 'fn';\n\treadonly getter: 'get';\n", "\treadonly static: 'shared';\n")).toEqual([]);
	});

	it("reports a segment's synonym that is a sibling segment, or a sibling's synonym", async () => {
		expect(await synonyms("\treadonly function: 'method';\n")).toEqual(['declaration.function: the synonym method is the sibling segment declaration.method']);
		expect(await synonyms("\treadonly function: 'fn';\n\treadonly method: 'fn';\n")).toEqual([
			'declaration.function: the synonym fn is also a synonym of the sibling declaration.method'
		]);
	});

	it("reports a segment's synonym that is a flag of its parent or a kind above it, or that flag's synonym", async () => {
		expect(await synonyms("\treadonly getter: 'static';\n")).toEqual(['declaration.method.getter: the synonym static is the flag static, which declaration.method has']);
		expect(await synonyms("\treadonly getter: 'shared';\n", "\treadonly static: 'shared';\n")).toEqual([
			'declaration.method.getter: the synonym shared is a synonym of the flag static, which declaration.method has',
			'#static: the synonym shared spells declaration.method.getter, beneath kinds that have the flag'
		]);
	});

	it("reports a flag's synonym that is a flag or another flag's synonym", async () => {
		expect(await synonyms('', "\treadonly static: 'async';\n")).toEqual(['#static: the synonym async is the flag async']);
		expect(await synonyms('', "\treadonly async: 'shared';\n\treadonly static: 'shared';\n")).toEqual(['#async: the synonym shared is also a synonym of the flag static']);
	});

	it("reports a flag's synonym that is a member of a kind with the flag, or a segment or synonym beneath one", async () => {
		expect(await synonyms('', "\treadonly static: 'accessor';\n")).toEqual([
			'#static: the synonym accessor is a member of declaration.method, declaration.method.getter, which have the flag'
		]);
		expect(await synonyms('', "\treadonly static: 'getter';\n")).toEqual(['#static: the synonym getter spells declaration.method.getter, beneath kinds that have the flag']);
	});

	it('reports a synonym not spelled as a segment', async () => {
		expect(await synonyms("\treadonly function: 'Fn';\n", "\treadonly static: 'class_';\n")).toEqual([
			'declaration.function: the synonym Fn is not spelled as a segment, in lower case with its words joined by _',
			'#static: the synonym class_ is not spelled as a segment, in lower case with its words joined by _'
		]);
	});

	it('reports a table entry with no position: a segment the level does not have, or a flag no kind has', async () => {
		expect(await synonyms("\treadonly closure: 'lambda';\n", "\treadonly shared: 'common';\n")).toEqual([
			'declaration: the synonyms of closure have no position, since closure is no segment of the level',
			"#shared: the flags' synonyms name it, and no kind has it as a flag"
		]);
	});
});

describe('generate', () => {
	it('renders nothing for a plan with issues, so the issues are reported rather than thrown', async () => {
		const dir = vocabulary({ ...CLEAN, ...MACROS });
		const { plan: p, files } = await generate(dir);
		expect([p.issues.length, files.size]).toEqual([1, 0]);
		expect(await vocabularyFeatureIssues(dir)).toEqual(p.issues);
	});
});

describe('the generated files', () => {
	const dir = vocabulary(CLEAN);
	let source: VocabularySource;
	let p: Plan;
	beforeAll(async () => {
		source = await readVocabularySource(dir);
		p = plan(source);
	});

	it('augment each kind a feature touches and declare every level, nested by namespace', async () => {
		expect(augmentation(source, p)).toBe(
			[
				HEADER,
				"import type { GrammarContext } from './context.ts';",
				"import type * as gate from './utils.ts';",
				"import type * as V from './index.ts';",
				"import type * as features from './features/index.ts';",
				"import type * as accessors from './features/methods/accessors/index.ts';",
				"import type * as asyncAwait from './features/async-await/index.ts';",
				"import type * as methods from './features/methods/index.ts';",
				'',
				"declare module './declaration.ts' {",
				'\tnamespace Declaration {',
				'\t\tinterface Function<G extends GrammarContext<G>> {',
				"\t\t\treadonly async?: gate.In<G, features.AsyncAwait, asyncAwait.Declaration.Function<G>['async']>;",
				'\t\t}',
				'\t\tinterface Method<G extends GrammarContext<G>> extends methods.Declaration.Method<G> {',
				"\t\t\treadonly accessor?: gate.In<G, features.Accessors, accessors.Declaration.Method<G>['accessor']>;",
				'\t\t}',
				'\t\tnamespace Method {',
				'\t\t\tinterface Getter<G extends GrammarContext<G>> extends methods.Declaration.Method.Getter<G> {',
				"\t\t\t\treadonly accessor: gate.In<G, features.Accessors, accessors.Declaration.Method.Getter<G>['accessor']>;",
				'\t\t\t}',
				'\t\t\ttype Any<G extends GrammarContext<G>> = V.Declaration.Method<G> | V.Declaration.Method.Getter<G>;',
				'\t\t}',
				'\t\ttype Any<G extends GrammarContext<G>> = V.Declaration<G> | V.Declaration.Function<G> | V.Declaration.Method<G> | V.Declaration.Method.Getter<G>;',
				'\t}',
				'}',
				''
			].join('\n')
		);
	});

	it('export every feature’s marker from the features index', async () => {
		expect(featuresIndex(p)).toBe(
			[
				HEADER,
				"export type { Accessors } from './methods/accessors/index.ts';",
				"export type { AsyncAwait } from './async-await/index.ts';",
				"export type { Methods } from './methods/index.ts';",
				''
			].join('\n')
		);
	});

	it('drift when missing or edited, and not once written', async () => {
		const { files } = await generate(dir);
		expect(drift(dir, files)).toEqual([`augment.ts: ${STALE}`, `features/index.ts: ${STALE}`]);
		for (const [file, text] of files) writeFileSync(join(dir, file), text);
		expect(await vocabularyFeatureIssues(dir)).toEqual([]);
		writeFileSync(join(dir, 'features/index.ts'), '');
		expect(await vocabularyFeatureIssues(dir)).toEqual([`features/index.ts: ${STALE}`]);
	});
});
