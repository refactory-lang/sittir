import { afterAll, describe, expect, it } from 'vitest';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { drift, generate, vocabularyFeatureIssues } from '../../src/vocabulary/index.ts';
import { plan } from '../../src/vocabulary/plan.ts';
import { readVocabularySource } from '../../src/vocabulary/read.ts';
import { augmentation, featuresIndex } from '../../src/vocabulary/write.ts';

const HEADER = '// Generated by `sittir tool vocabulary-features --write` from the feature folders: do not edit.';
const STALE = 'not what the feature folders generate; run sittir tool vocabulary-features --write';

const dirs: string[] = [];
afterAll(() => {
	for (const dir of dirs) rmSync(dir, { recursive: true, force: true });
});

function vocabulary(files: Readonly<Record<string, string>>): string {
	const dir = mkdtempSync(join(tmpdir(), 'vocabulary-features-'));
	dirs.push(dir);
	for (const [file, text] of Object.entries(files)) {
		mkdirSync(dirname(join(dir, file)), { recursive: true });
		writeFileSync(join(dir, file), text);
	}
	return dir;
}

function feature(dir: string, marker: string, stubs: Readonly<Record<string, string>>): Record<string, string> {
	const exports = Object.keys(stubs).map((file) => `export type * from './${file}';`);
	return {
		[`features/${dir}/index.ts`]: `${[...exports, marker].join('\n')}\n`,
		...Object.fromEntries(Object.entries(stubs).map(([file, text]) => [`features/${dir}/${file}`, text]))
	};
}

const DECLARATION = `export interface Declaration<G extends GrammarContext<G>> {
	readonly $kind: 'declaration';
	readonly name: G['identifier'];
}
export namespace Declaration {
	export interface Function<G extends GrammarContext<G>> extends SubKindOf<V.Declaration<G>> {
		readonly $kind: 'declaration.function';
		readonly parameters: readonly unknown[];
	}
}
`;

const ASYNC_AWAIT = feature('async-await', 'export interface AsyncAwait {\n\treadonly asyncAwait: true;\n}', {
	'declaration.ts': `export namespace Declaration {
	export interface Function<G extends GrammarContext<G>> {
		readonly async?: boolean;
	}
}
`
});

const METHODS = feature('methods', 'export interface Methods {\n\treadonly methods: true;\n}', {
	'declaration.ts': `export namespace Declaration {
	export interface Method<G extends GrammarContext<G>> extends SubKindOf<V.Declaration<G>> {
		readonly $kind: 'declaration.method';
		readonly static?: boolean;
	}
	export namespace Method {
		export interface Getter<G extends GrammarContext<G>> extends SubKindOf<V.Declaration.Method<G>> {
			readonly $kind: 'declaration.method.getter';
		}
	}
}
`
});

const ACCESSORS = feature('methods/accessors', 'export interface Accessors extends Methods {\n\treadonly accessors: true;\n}', {
	'declaration.ts': `export namespace Declaration {
	export interface Method<G extends GrammarContext<G>> {
		readonly accessor?: 'get' | 'set';
	}
	export namespace Method {
		export interface Getter<G extends GrammarContext<G>> {
			readonly accessor: 'get';
		}
	}
}
`
});

const CLEAN = { 'declaration.ts': DECLARATION, ...ASYNC_AWAIT, ...METHODS, ...ACCESSORS };

const issues = (files: Readonly<Record<string, string>>): readonly string[] => plan(readVocabularySource(vocabulary(files))).issues;

describe('the vocabulary', () => {
	it('has no feature issues, and its generated files are what its feature folders generate', async () => {
		expect(await vocabularyFeatureIssues()).toEqual([]);
	}, 60_000);
});

describe('plan', () => {
	const p = plan(readVocabularySource(vocabulary(CLEAN)));

	it('finds nothing wrong with a well-formed feature tree', () => {
		expect([...p.issues, ...p.notes]).toEqual([]);
	});

	it('gives each kind a feature adds to that feature', () => {
		expect(Object.fromEntries([...p.kinds].map(([path, k]) => [path, k.feature?.name]))).toEqual({
			declaration: undefined,
			'declaration.function': undefined,
			'declaration.method': 'Methods',
			'declaration.method.getter': 'Methods'
		});
	});

	it('gates a member a stub adds to a kind it does not declare, and leaves a kind’s own members to the kind', () => {
		expect(Object.fromEntries([...p.owned].map(([path, members]) => [path, Object.fromEntries([...members].map(([name, o]) => [name, o.feature.name]))]))).toEqual({
			'declaration.function': { async: 'AsyncAwait' },
			'declaration.method': { accessor: 'Accessors' },
			'declaration.method.getter': { accessor: 'Accessors' }
		});
	});

	it('makes every proper prefix of a kind a level holding each kind at or under it', () => {
		expect(Object.fromEntries(p.levels)).toEqual({
			Declaration: ['Declaration', 'Declaration.Function', 'Declaration.Method', 'Declaration.Method.Getter'],
			'Declaration.Method': ['Declaration.Method', 'Declaration.Method.Getter']
		});
	});

	it('reports a member two features own', () => {
		const properties = feature('properties', 'export interface Properties {\n\treadonly properties: true;\n}', {
			'declaration.ts': `export namespace Declaration {
	export interface Method<G extends GrammarContext<G>> {
		readonly accessor?: boolean;
	}
}
`
		});
		expect(issues({ ...CLEAN, ...properties })).toEqual(['declaration.method.accessor: owned by Accessors and Properties']);
	});

	it('reports members added to a kind the vocabulary does not declare', () => {
		const lambda = feature('async-await', 'export interface AsyncAwait {\n\treadonly asyncAwait: true;\n}', {
			'declaration.ts': `export namespace Declaration {
	export interface Lambda<G extends GrammarContext<G>> {
		readonly async?: boolean;
	}
}
`
		});
		expect(issues({ ...CLEAN, ...lambda })).toEqual(['AsyncAwait: Declaration.Lambda adds members to a kind the vocabulary does not declare']);
	});

	it('lets a feature require a member only when it extends the feature that owns it', () => {
		const generators = (marker: string): Record<string, string> =>
			feature('generators', marker, {
				'declaration.ts': `export namespace Declaration {
	export interface Function<G extends GrammarContext<G>> {
		readonly async: boolean;
	}
}
`
			});
		expect(issues({ ...CLEAN, ...generators('export interface Generators {\n\treadonly generators: true;\n}') })).toEqual([
			'Generators restates declaration.function.async, which AsyncAwait owns, and does not extend AsyncAwait'
		]);
		expect(issues({ ...CLEAN, ...generators('export interface Generators extends AsyncAwait {\n\treadonly generators: true;\n}') })).toEqual([]);
	});

	it('reports a base declaration of a member a feature gates on the same line', () => {
		const arrow = DECLARATION.replace(
			'\t}\n}\n',
			`\t}
	export namespace Function {
		export interface Arrow<G extends GrammarContext<G>> extends SubKindOf<V.Declaration.Function<G>> {
			readonly $kind: 'declaration.function.arrow';
			readonly async?: boolean;
		}
	}
}
`
		);
		const p = plan(readVocabularySource(vocabulary({ ...CLEAN, 'declaration.ts': arrow })));
		expect(p.issues).toEqual(['AsyncAwait owns async at declaration.function, and the kind declares it at declaration.function.arrow, which inherits it']);
		expect(p.notes).toEqual(['async is gated at some kinds and stays in the base at 1: declaration.function.arrow']);
	});

	it('reports a feature whose folder sits in another feature’s folder without extending it', () => {
		const getters = feature('methods/getters', 'export interface Getters {\n\treadonly getters: true;\n}', {});
		expect(issues({ ...CLEAN, ...getters })).toEqual(['Getters sits in features/methods but does not extend Methods']);
	});
});

describe('the generated files', () => {
	const dir = vocabulary(CLEAN);
	const source = readVocabularySource(dir);
	const p = plan(source);

	it('augment each kind a feature touches and declare every level, nested by namespace', () => {
		expect(augmentation(source, p)).toBe(
			[
				HEADER,
				"import type { GrammarContext } from './context.ts';",
				"import type * as gate from './utils.ts';",
				"import type * as V from './index.ts';",
				"import type * as features from './features/index.ts';",
				"import type * as accessors from './features/methods/accessors/index.ts';",
				"import type * as asyncAwait from './features/async-await/index.ts';",
				"import type * as methods from './features/methods/index.ts';",
				'',
				"declare module './declaration.ts' {",
				'\tnamespace Declaration {',
				'\t\tinterface Function<G extends GrammarContext<G>> {',
				"\t\t\treadonly async?: gate.In<G, features.AsyncAwait, asyncAwait.Declaration.Function<G>['async']>;",
				'\t\t}',
				'\t\tinterface Method<G extends GrammarContext<G>> extends methods.Declaration.Method<G> {',
				"\t\t\treadonly accessor?: gate.In<G, features.Accessors, accessors.Declaration.Method<G>['accessor']>;",
				'\t\t}',
				'\t\tnamespace Method {',
				'\t\t\tinterface Getter<G extends GrammarContext<G>> extends methods.Declaration.Method.Getter<G> {',
				"\t\t\t\treadonly accessor: gate.In<G, features.Accessors, accessors.Declaration.Method.Getter<G>['accessor']>;",
				'\t\t\t}',
				'\t\t\ttype Any<G extends GrammarContext<G>> = V.Declaration.Method<G> | V.Declaration.Method.Getter<G>;',
				'\t\t}',
				'\t\ttype Any<G extends GrammarContext<G>> = V.Declaration<G> | V.Declaration.Function<G> | V.Declaration.Method<G> | V.Declaration.Method.Getter<G>;',
				'\t}',
				'}',
				''
			].join('\n')
		);
	});

	it('export every feature’s marker from the features index', () => {
		expect(featuresIndex(p)).toBe(
			[
				HEADER,
				"export type { Accessors } from './methods/accessors/index.ts';",
				"export type { AsyncAwait } from './async-await/index.ts';",
				"export type { Methods } from './methods/index.ts';",
				''
			].join('\n')
		);
	});

	it('drift when missing or edited, and not once written', async () => {
		const { files } = await generate(dir);
		expect(drift(dir, files)).toEqual([`augment.ts: ${STALE}`, `features/index.ts: ${STALE}`]);
		for (const [file, text] of files) writeFileSync(join(dir, file), text);
		expect(await vocabularyFeatureIssues(dir)).toEqual([]);
		writeFileSync(join(dir, 'features/index.ts'), '');
		expect(await vocabularyFeatureIssues(dir)).toEqual([`features/index.ts: ${STALE}`]);
	});
});
