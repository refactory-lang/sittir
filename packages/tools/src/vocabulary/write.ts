import { type Owned, type Plan, stubAlias, under } from './plan.ts';
import { AUGMENTATION, FEATURES, SUB_KIND_OF, type Feature, type VocabularySource, byCodepoint } from '@sittir/codegen/bindings';

export const FEATURES_INDEX = `${FEATURES}/index.ts`;
export const GENERATED_FILES: readonly string[] = [AUGMENTATION, FEATURES_INDEX];
export const UNFIT_RESTATED = 'unfit-restated.json';
export const RESTATED_TEST = 'vocabulary-restated.test-d.ts';

export type UnfitRestated = Readonly<Record<string, Readonly<Record<string, string>>>>;

const MAP = 'map.ts';

const HEADER = '// Generated by `sittir tool vocabulary-features --write` from the feature folders: do not edit.';
const RESTATED_HEADER = '// Generated by `sittir tool vocabulary-features --write` from the members each kind restates: do not edit.';
const DECLARED_PATH = /= '([^']+)'>\s+extends\s/;
const STRING_LITERAL = /'([^']*)'/g;
const HERITAGE_END = /\bextends\s+$/;

export function restatedHeritage(text: string, restatedOf: (path: string) => readonly string[]): { readonly text: string; readonly paths: readonly string[] } {
	const paths: string[] = [];
	const head = `${SUB_KIND_OF}<`;
	let out = '';
	let from = 0;
	for (let open = text.indexOf(head); open >= 0; open = text.indexOf(head, from)) {
		if (!HERITAGE_END.test(text.slice(0, open))) {
			out += text.slice(from, open + head.length);
			from = open + head.length;
			continue;
		}
		const declared = text.slice(text.lastIndexOf('interface ', open), open);
		const path = DECLARED_PATH.exec(declared)?.[1];
		if (path === undefined) throw new Error(`vocabulary: a ${SUB_KIND_OF} heritage on a declaration with no path: ${declared.trim()}`);
		const start = open + head.length;
		let depth = 1;
		let comma: number | undefined;
		let end = start;
		for (; end < text.length && depth > 0; end++) {
			const c = text[end];
			if (c === '<') depth++;
			else if (c === '>') depth--;
			else if (c === ',' && depth === 1) comma ??= end;
		}
		paths.push(path);
		const close = end - 1;
		const names = restatedOf(path);
		const listed = comma === undefined ? [] : [...text.slice(comma + 1, close).matchAll(STRING_LITERAL)].map((m) => m[1]!);
		const parent = text.slice(start, comma ?? close).trim();
		out += text.slice(from, start);
		out += listed.join('|') === names.join('|') ? text.slice(start, close) : names.length === 0 ? parent : `${parent}, ${names.map((name) => `'${name}'`).join(' | ')}`;
		from = close;
	}
	return { text: out + text.slice(from), paths };
}

export interface RestatedTestInput {
	readonly map: string;
	readonly vocabularyModule: string;
	readonly mapModule: string;
	readonly composed: ReadonlySet<string>;
	readonly unfit: UnfitRestated;
}

export function restatedChecks(p: Plan, composed: ReadonlySet<string>): ReadonlyMap<string, readonly string[]> {
	const present = (feature: Feature | undefined): boolean => feature === undefined || composed.has(feature.name);
	return new Map(
		[...p.kinds.values()]
			.filter((kind) => kind.restated.length > 0 && present(kind.feature))
			.map((kind) => [kind.path, kind.restated.filter((name) => present(p.owned.get(kind.path)?.get(name)?.feature))] as const)
			.filter(([, names]) => names.length > 0)
			.sort(([a], [b]) => byCodepoint(a, b))
	);
}

export function restatedTest(p: Plan, input: RestatedTestInput): string {
	const blocks = [...restatedChecks(p, input.composed)].flatMap(([path, names]) => {
		const kind = p.kinds.get(path)!;
		const parent = kind.parent === undefined ? undefined : p.kinds.get(kind.parent);
		if (parent === undefined) throw new Error(`vocabulary: ${path} restates ${names.join(', ')} and has no parent`);
		return [
			'',
			`export declare namespace ${kind.qname} {`,
			`\ttype Child = V.${kind.qname}<${input.map}>;`,
			`\ttype Parent = V.${parent.qname}<${input.map}, '${path}'>;`,
			'\tinterface Restated {',
			...names.flatMap((name) => {
				const reason = input.unfit[path]?.[name];
				return [...(reason === undefined ? [] : [`\t\t// @ts-expect-error ${reason}`]), `\t\treadonly ${name}: Fit<Child['${name}'], Parent['${name}']>;`];
			}),
			'\t}',
			'}'
		];
	});
	return [
		RESTATED_HEADER,
		`import type * as V from '${input.vocabularyModule}';`,
		`import type { ${input.map} } from '${input.mapModule}';`,
		'',
		'type Fit<C extends P, P> = C;',
		...blocks,
		''
	].join('\n');
}

interface Entry {
	readonly qname: string;
	readonly lines: readonly string[];
}

interface Node {
	entry: Entry | undefined;
	readonly children: Map<string, Node>;
}

const lastSegment = (qname: string): string => qname.slice(qname.lastIndexOf('.') + 1);

const levelsLast = (a: string, b: string): number => (a === 'Any') === (b === 'Any') ? byCodepoint(a, b) : a === 'Any' ? 1 : -1;

function nest(entries: readonly Entry[], indent: string): string[] {
	const root: Node = { entry: undefined, children: new Map() };
	for (const e of entries) {
		let node = root;
		for (const segment of e.qname.split('.')) {
			const next = node.children.get(segment) ?? { entry: undefined, children: new Map<string, Node>() };
			node.children.set(segment, next);
			node = next;
		}
		if (node.entry !== undefined) throw new Error(`${e.qname}: two entries`);
		node.entry = e;
	}
	const emit = (node: Node, name: string, at: string): string[] => {
		const { entry } = node;
		const out = entry === undefined ? [] : entry.lines.map((line, i) => (i === 0 || i === entry.lines.length - 1 ? `${at}${line}` : `${at}\t${line}`));
		if (node.children.size > 0) {
			out.push(`${at}namespace ${name} {`);
			for (const [segment, child] of [...node.children].sort(([a], [b]) => levelsLast(a, b))) out.push(...emit(child, segment, `${at}\t`));
			out.push(`${at}}`);
		}
		return out;
	};
	return [...root.children].sort(([a], [b]) => levelsLast(a, b)).flatMap(([segment, child]) => emit(child, segment, indent));
}

export function augmentation(source: VocabularySource, p: Plan): string {
	const byModule = new Map<string, Entry[]>();
	const add = (qname: string, lines: readonly string[]): void => {
		const top = qname.replace(/\..*$/, '');
		const file = source.modules.get(top);
		if (file === undefined) throw new Error(`${qname}: no namespace file declares ${top}`);
		byModule.set(file, [...(byModule.get(file) ?? []), { qname, lines }]);
	};
	const used = new Set<Feature>();
	const alias = (feature: Feature): string => {
		used.add(feature);
		return stubAlias(feature);
	};
	let gated = false;
	let headed = false;
	for (const kind of p.kinds.values()) {
		if (kind.text) {
			if (kind.feature !== undefined) add(kind.qname, [`type ${lastSegment(kind.qname)}<G extends GrammarMap> = ${alias(kind.feature)}.${kind.qname}<G>;`]);
			continue;
		}
		const slots = [...(p.owned.get(kind.path) ?? new Map<string, Owned>())].sort(([a], [b]) => byCodepoint(a, b));
		if (kind.feature === undefined && slots.length === 0) continue;
		gated ||= slots.length > 0;
		headed = true;
		const head = `interface ${lastSegment(kind.qname)}<G extends GrammarMap, K extends gate.Under<'${kind.path}'> = '${kind.path}'>${kind.feature === undefined ? '' : ` extends ${alias(kind.feature)}.${kind.qname}<G, K>`}`;
		const lines = slots.map(
			([name, o]) =>
				`readonly ${name}${o.slot.optional ? '?' : ''}: gate.In<G, features.${o.feature.name}, ${alias(o.feature)}.${kind.qname}<G, K>['${name}']>;`
		);
		add(kind.qname, lines.length === 0 ? [`${head} {}`] : [`${head} {`, ...lines, '}']);
	}
	for (const { name, targetName, feature } of p.aliases) {
		if (feature === undefined) continue;
		gated = true;
		headed = true;
		add(name, [`type ${lastSegment(name)}<G extends GrammarMap> = gate.In<G, features.${feature}, V.${targetName}<G>>;`]);
	}
	for (const [name, feature] of p.shared) add(name, [`type ${lastSegment(name)}<G extends GrammarMap> = ${alias(feature)}.${name}<G>;`]);
	const pathOf = new Map([...p.kinds.values()].map((kind) => [kind.qname, kind.path]));
	const byName = new Map([...p.kinds.values()].map((kind) => [kind.qname, kind]));
	const gatedBy = (qname: string, type: string): string => {
		const feature = byName.get(qname)?.feature;
		return feature === undefined ? type : `gate.In<G, features.${feature.name}, ${type}>`;
	};
	const flagged = [...p.flags].filter(([, flags]) => flags.size > 0).sort(([a], [b]) => byCodepoint(a, b));
	const flagRow = ([path, flags]: readonly [string, ReadonlyMap<string, Feature | undefined>]): string =>
		`\t\treadonly '${path}': { ${[...flags]
			.sort(([a], [b]) => byCodepoint(a, b))
			.map(([name, feature]) => `readonly ${name}: ${feature === undefined ? 'object' : `features.${feature.name}`}`)
			.join('; ')} };`;
	gated ||= flagged.some(([, flags]) => [...flags.values()].some((feature) => feature !== undefined));
	const mixed = source.texts;
	const stated = mixed.filter((key) => p.kinds.get(key)?.text === true);
	if (stated.length > 0) throw new Error(`vocabulary: TextPaths lists ${stated.join(', ')}, which the vocabulary declares as Text; list only kinds a token may also read as`);
	for (const [ns, arms] of p.levels) {
		const path = pathOf.get(ns);
		const texts = path === undefined ? [] : mixed.filter((key) => under(key, path)).map((key) => `Text<G, '${key}'>`);
		add(`${ns}.Any`, [`type Any<G extends GrammarMap> = ${[...arms.map((q) => `V.${q}<G>`), ...texts].join(' | ')};`]);
	}
	return [
		HEADER,
		`import type { GrammarMap${mixed.length > 0 ? ', Text' : ''} } from './${MAP}';`,
		...(headed ? ["import type * as gate from './utils.ts';"] : []),
		"import type * as V from './index.ts';",
		...(gated ? [`import type * as features from './${FEATURES_INDEX}';`] : []),
		...[...used]
			.sort((a, b) => byCodepoint(stubAlias(a), stubAlias(b)))
			.map((f) => `import type * as ${stubAlias(f)} from './${FEATURES}/${f.dir}/index.ts';`),
		'',
		...[...byModule].sort(([a], [b]) => byCodepoint(a, b)).flatMap(([file, entries]) => [`declare module './${file}' {`, ...nest(entries, '\t'), '}', '']),
		`declare module './${MAP}' {`,
		'\tinterface Paths<G extends GrammarMap> {',
		...[...p.kinds.values()].sort((a, b) => byCodepoint(a.path, b.path)).map((kind) => `\t\treadonly '${kind.path}': ${gatedBy(kind.qname, `V.${kind.qname}<G>`)};`),
		'\t}',
		'}',
		...(flagged.length === 0 ? [] : ['', "declare module './utils.ts' {", '\tinterface FlagFeatures {', ...flagged.map(flagRow), '\t}', '}']),
		''
	].join('\n');
}

export function featuresIndex(p: Plan): string {
	return [
		HEADER,
		...[...p.features.values()].sort((a, b) => byCodepoint(a.name, b.name)).map((f) => `export type { ${f.name} } from './${f.dir}/index.ts';`),
		''
	].join('\n');
}
