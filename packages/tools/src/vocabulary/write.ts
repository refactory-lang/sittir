import { type Owned, type Plan, stubAlias } from './plan.ts';
import { AUGMENTATION, FEATURES, type Feature, type VocabularySource, byCodepoint } from './read.ts';

export const FEATURES_INDEX = `${FEATURES}/index.ts`;
export const GENERATED_FILES: readonly string[] = [AUGMENTATION, FEATURES_INDEX];

const HEADER = '// Generated by `sittir tool vocabulary-features --write` from the feature folders: do not edit.';

interface Entry {
	readonly qname: string;
	readonly lines: readonly string[];
}

interface Node {
	entry: Entry | undefined;
	readonly children: Map<string, Node>;
}

const lastSegment = (qname: string): string => qname.slice(qname.lastIndexOf('.') + 1);

const levelsLast = (a: string, b: string): number => (a === 'Any') === (b === 'Any') ? byCodepoint(a, b) : a === 'Any' ? 1 : -1;

function nest(entries: readonly Entry[], indent: string): string[] {
	const root: Node = { entry: undefined, children: new Map() };
	for (const e of entries) {
		let node = root;
		for (const segment of e.qname.split('.')) {
			const next = node.children.get(segment) ?? { entry: undefined, children: new Map<string, Node>() };
			node.children.set(segment, next);
			node = next;
		}
		if (node.entry !== undefined) throw new Error(`${e.qname}: two entries`);
		node.entry = e;
	}
	const emit = (node: Node, name: string, at: string): string[] => {
		const { entry } = node;
		const out = entry === undefined ? [] : entry.lines.map((line, i) => (i === 0 || i === entry.lines.length - 1 ? `${at}${line}` : `${at}\t${line}`));
		if (node.children.size > 0) {
			out.push(`${at}namespace ${name} {`);
			for (const [segment, child] of [...node.children].sort(([a], [b]) => levelsLast(a, b))) out.push(...emit(child, segment, `${at}\t`));
			out.push(`${at}}`);
		}
		return out;
	};
	return [...root.children].sort(([a], [b]) => levelsLast(a, b)).flatMap(([segment, child]) => emit(child, segment, indent));
}

export function augmentation(source: VocabularySource, p: Plan): string {
	const byModule = new Map<string, Entry[]>();
	const add = (qname: string, lines: readonly string[]): void => {
		const top = qname.replace(/\..*$/, '');
		const file = source.modules.get(top);
		if (file === undefined) throw new Error(`${qname}: no namespace file declares ${top}`);
		byModule.set(file, [...(byModule.get(file) ?? []), { qname, lines }]);
	};
	const used = new Set<Feature>();
	const alias = (feature: Feature): string => {
		used.add(feature);
		return stubAlias(feature);
	};
	let gated = false;
	for (const kind of p.kinds.values()) {
		const members = [...(p.owned.get(kind.path) ?? new Map<string, Owned>())].sort(([a], [b]) => byCodepoint(a, b));
		if (kind.feature === undefined && members.length === 0) continue;
		gated ||= members.length > 0;
		const head = `interface ${lastSegment(kind.qname)}<G extends GrammarContext<G>>${kind.feature === undefined ? '' : ` extends ${alias(kind.feature)}.${kind.qname}<G>`}`;
		const lines = members.map(
			([name, o]) =>
				`readonly ${name}${o.member.optional ? '?' : ''}: gate.In<G, features.${o.feature.name}, ${alias(o.feature)}.${kind.qname}<G>['${name}']>;`
		);
		add(kind.qname, lines.length === 0 ? [`${head} {}`] : [`${head} {`, ...lines, '}']);
	}
	for (const v of p.values.values()) {
		const { member, enumeration, feature } = v.enumerated;
		const pin = `gate.AtOrBeneath<V.${enumeration.name}, '${v.value}'>`;
		gated ||= feature !== undefined;
		add(v.qname, [
			`interface ${lastSegment(v.qname)}<G extends GrammarContext<G>> extends gate.SubKindOf<V.${v.parent}<G>> {`,
			`readonly $kind: '${v.path}';`,
			`readonly ${member}: ${feature === undefined ? pin : `gate.In<G, features.${feature.name}, ${pin}>`};`,
			'}'
		]);
	}
	for (const [ns, arms] of p.levels) add(`${ns}.Any`, [`type Any<G extends GrammarContext<G>> = ${arms.map((q) => `V.${q}<G>`).join(' | ')};`]);
	return [
		HEADER,
		"import type { GrammarContext } from './context.ts';",
		...(gated || p.values.size > 0 ? ["import type * as gate from './utils.ts';"] : []),
		"import type * as V from './index.ts';",
		...(gated ? [`import type * as features from './${FEATURES_INDEX}';`] : []),
		...[...used]
			.sort((a, b) => byCodepoint(stubAlias(a), stubAlias(b)))
			.map((f) => `import type * as ${stubAlias(f)} from './${FEATURES}/${f.dir}/index.ts';`),
		'',
		...[...byModule].sort(([a], [b]) => byCodepoint(a, b)).flatMap(([file, entries]) => [`declare module './${file}' {`, ...nest(entries, '\t'), '}', ''])
	].join('\n');
}

export function featuresIndex(p: Plan): string {
	return [
		HEADER,
		...[...p.features.values()].sort((a, b) => byCodepoint(a.name, b.name)).map((f) => `export type { ${f.name} } from './${f.dir}/index.ts';`),
		''
	].join('\n');
}
