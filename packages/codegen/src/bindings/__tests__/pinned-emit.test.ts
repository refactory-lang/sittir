import type { PortableContainer, PortableSeat } from '@sittir/types';
import { describe, expect, it } from 'vitest';
import { runPinned } from '../read.ts';

describe('the pinned child emits a portable build module', () => {
	it('writes the module through the pinned builders and returns its text and diagnostics', async () => {
		const { text, diagnostics } = await runPinned('portableBuild', {
			grammar: 'python',
			api: 'PythonAPI',
			map: 'PythonMap',
			imports: { vocabulary: '@sittir/types/vocabulary', api: '../api.js', map: './map.js' },
			table: {
				builders: { passStatement: 'nullary' },
				paths: { 'statement.pass': { root: true, arms: [{ kind: 1, builder: 'passStatement', when: [], members: [], presets: [], flags: {} }] } }
			},
			members: {},
			viewed: [],
			textPaths: [],
			textInputs: [],
			textValues: [],
			holes: [],
				decided: {}
		});
		expect(diagnostics).toEqual([]);
		expect(text.startsWith('// Auto-generated by @sittir/codegen — do not edit\n')).toBe(true);
		expect(text).toContain('export function portableBuild(engine: Engine<PythonAPI>)');
		expect(text).toContain('b.passStatement()');
		expect(text).toContain('const statement_pass$1 = (_input: PathInput<');
		expect(text).toContain('pass: statement_pass');
		expect(text).not.toContain('unbuilt');
	}, 60_000);

	it('writes only the functions a generated path reaches', async () => {
		const { text, diagnostics } = await runPinned('portableBuild', {
			grammar: 'python',
			api: 'PythonAPI',
			map: 'PythonMap',
			imports: { vocabulary: '@sittir/types/vocabulary', api: '../api.js', map: './map.js' },
			table: {
				builders: { passStatement: 'nullary', breakStatement: 'nullary' },
				paths: {
					'statement.pass': { root: true, arms: [{ kind: 1, builder: 'passStatement', when: [], members: [], presets: [], flags: {} }] },
					'statement.jump': {
						root: true,
						arms: [
							{ kind: 2, builder: 'breakStatement', when: [{ flag: 'loud', set: true }], members: [], presets: [], flags: {} },
							{ kind: 3, when: [], members: [], presets: [], flags: {} }
						]
					}
				}
			},
			members: {},
			viewed: [],
			textPaths: [],
			textInputs: [],
			textValues: [],
			holes: [],
				decided: {}
		});
		expect(diagnostics.map(({ code, path }) => [code, path])).toEqual([['portable-emit-unfit-member', 'statement.jump']]);
		expect(text).toContain('const statement_pass$1 = ');
		expect(text).not.toContain('statement_jump');
	}, 60_000);

	it('spells a text holding a backslash or a quote as escapes in the string it writes', async () => {
		const { text, diagnostics } = await runPinned('portableBuild', {
			grammar: 'python',
			api: 'PythonAPI',
			map: 'PythonMap',
			imports: { vocabulary: '@sittir/types/vocabulary', api: '../api.js', map: './map.js' },
			table: {
				builders: { lineContinuation: 'config' },
				paths: { 'element.continuation': { root: true, arms: [{ kind: 2, builder: 'lineContinuation', when: [], members: [], presets: [{ steps: [{ key: 'text' }], text: "\\'" }], flags: {} }] } }
			},
			members: {},
			viewed: [],
			textPaths: [],
			textInputs: [],
			textValues: [],
			holes: [],
				decided: {}
		});
		expect(diagnostics).toEqual([]);
		expect(text).toContain("b.lineContinuation({ text: '\\\\\\'' })");
	}, 60_000);

	it.each([
		[[], false],
		[[[1, 'elements']], true]
	] as const)('places a passed node by its seat kinds, and returns a hole only where the seat takes holes: %j', async (holes, holed) => {
		const { text, diagnostics } = await runPinned('portableBuild', {
			grammar: 'typescript',
			api: 'TypeScriptAPI',
			map: 'TypeScriptMap',
			imports: { vocabulary: '@sittir/types/vocabulary', api: '../api.js', map: './map.js' },
			table: {
				builders: { array: 'spread' },
				paths: {
					'expression.collection.list': { root: true, arms: [{ kind: 1, builder: 'array', when: [], members: [{ name: 'elements', steps: [{ key: 'elements' }], multiple: true, seats: [{ at: [1, 'elements'], kinds: [7, 9] }] }], presets: [], flags: {} }] }
				}
			},
			members: { 'expression.collection.list': { elements: { paths: [], texts: [], unmapped: [], string: false, optional: true } } },
			viewed: [],
			textPaths: [],
			textInputs: [],
			textValues: [],
			holes,
			decided: {}
		});
		expect(diagnostics).toEqual([]);
		expect(text).toContain('if (seated(value, [7, 9])) return value;');
		expect(text).toContain("return unseated('expression.collection.list.elements', value);");
		expect(text.includes('if (value === null) return null;')).toBe(holed);
	}, 60_000);

	it('spells a guarded list as its first item and the rest, guards an optional member, and types a token member by its texts', async () => {
		const { text, diagnostics } = await runPinned('portableBuild', {
			grammar: 'python',
			api: 'PythonAPI',
			map: 'PythonMap',
			imports: { vocabulary: '@sittir/types/vocabulary', api: '../api.js', map: './map.js' },
			table: {
				builders: { block: 'config', blockBody: 'spread' },
				paths: {
					'statement.block': {
						root: true,
						arms: [
							{
								kind: 1,
								builder: 'block',
								when: [],
								members: [
									{ name: 'statements', steps: [{ key: 'body', optional: true }], multiple: false, list: true, seats: [{ at: [1, 'body'], kinds: [7], many: true, within: [{ key: 'body', builder: 'blockBody' }] }] },
									{ name: 'label', steps: [{ key: 'label' }], multiple: false, seats: [{ at: [1, 'label'], kinds: [8, 9], tokens: { a: 8, b: 9 } }] }
								],
								presets: [],
								flags: {}
							}
						]
					}
				}
			},
			members: {
				'statement.block': {
					statements: { paths: [], texts: [], unmapped: [], string: false, optional: true },
					label: { paths: [], texts: ['a', 'b'], unmapped: [], string: false, optional: true }
				}
			},
			viewed: [],
			textPaths: [],
			textInputs: [],
			textValues: [],
			holes: [],
				decided: {}
		});
		expect(diagnostics).toEqual([]);
		expect(text).toContain('const statements$first = (input.statements ?? [])[0];');
		expect(text).toContain('const statements$rest = (input.statements ?? []).slice(1);');
		expect(text).toContain('statements$first === undefined ? undefined : b.blockBody(statement_block$1_statements$item(statements$first), ...statements$rest.map(statement_block$1_statements$item))');
		expect(text).toContain("input.label === undefined ? missing('statement.block.label') : statement_block$1_label(input.label)");
		expect(text).toContain("const statement_block$1_label = (value: 'a' | 'b') =>");
	}, 60_000);

	it('picks a value-built path\'s arm by its scalar, and passes the scalar to the arm\'s builder', async () => {
		const { text, diagnostics } = await runPinned('portableBuild', {
			grammar: 'typescript',
			api: 'TypeScriptAPI',
			map: 'TypeScriptMap',
			imports: { vocabulary: '@sittir/types/vocabulary', api: '../api.js', map: './map.js' },
			table: {
				builders: { numberDecimal: 'text', numberBigint: 'direct' },
				paths: {
					'literal.number': {
						root: true,
						builds: { integer: 5, bigint: 6 },
						arms: [
							{ kind: 5, builder: 'numberDecimal', scalar: 'integer', when: [], members: [], presets: [], flags: {} },
							{ kind: 6, builder: 'numberBigint', scalar: 'bigint', numeric: ['content'], when: [], members: [], presets: [], flags: {} }
						]
					}
				}
			},
			members: {},
			viewed: [],
			textPaths: [],
			textInputs: [],
			textValues: [],
			holes: [],
				decided: {}
		});
		expect(diagnostics).toEqual([]);
		expect(text).toContain("if (typeof input.$value === 'bigint') return literal_number$6(input);");
		expect(text).toContain("if (typeof input.$value === 'number') return literal_number$5(input);");
		expect(text).toContain('return b.numberDecimal(input.$value);');
		expect(text).toContain('return b.numberBigint(input.$value);');
		expect(text).toContain("return unbuilt('literal.number', input);");
	}, 60_000);

	it('leaves out a member that takes one value or a list, and wraps a single value in an elements container', async () => {
		const run = (seats: readonly PortableSeat[]) =>
			runPinned('portableBuild', {
				grammar: 'python',
				api: 'PythonAPI',
				map: 'PythonMap',
				imports: { vocabulary: '@sittir/types/vocabulary', api: '../api.js', map: './map.js' },
				table: {
					builders: { call: 'config', argumentList: 'config', argumentListElements: 'elements' },
					paths: { 'expression.call': { root: true, arms: [{ kind: 1, builder: 'call', when: [], members: [{ name: 'arguments', steps: [{ key: 'arguments' }], multiple: false, seats }], presets: [], flags: {} }] } }
				},
				members: { 'expression.call': { arguments: { paths: [], texts: [], unmapped: [], string: false, optional: false } } },
				viewed: [],
				textPaths: [],
				textInputs: [],
				textValues: [],
				holes: [],
				decided: {}
			});
		const within: readonly PortableContainer[] = [{ builder: 'argumentList', key: 'arguments' }, { builder: 'argumentListElements', key: 'items' }];
		const listed = await run([{ at: [1, 'arguments'], kinds: [2] }, { at: [3, 'items'], kinds: [4], within, many: true }]);
		expect(listed.diagnostics.map(({ code, message }) => [code, message])).toEqual([['portable-emit-unfit-member', 'arguments takes one value or a list']]);
		const single = await run([{ at: [3, 'items'], kinds: [4], within }]);
		expect(single.diagnostics).toEqual([]);
		expect(single.text).toContain('return b.argumentList({ arguments: b.argumentListElements(value) });');
	}, 60_000);

	it.each([
		[['literal.string.text'], true],
		[[], false]
	] as const)('builds a text-built arm from its text only where the path reads its $value as text: %j', async (textValues, built) => {
		const { text, diagnostics } = await runPinned('portableBuild', {
			grammar: 'python',
			api: 'PythonAPI',
			map: 'PythonMap',
			imports: { vocabulary: '@sittir/types/vocabulary', api: '../api.js', map: './map.js' },
			table: { builders: { stringFragment: 'text' }, paths: { 'literal.string.text': { root: true, arms: [{ kind: 1, builder: 'stringFragment', when: [], members: [], presets: [], flags: {} }] } } },
			members: {},
			viewed: [],
			textPaths: [],
			textInputs: ['literal.string.text'],
			textValues,
			holes: [],
				decided: {}
		});
		expect(text.includes("return b.stringFragment(typeof input === 'string' ? input : input.$value);")).toBe(built);
		expect(diagnostics.map(({ code }) => code)).toEqual(built ? [] : ['portable-emit-unfit-member']);
	}, 60_000);

	it.each([
		[['statement.block'], false],
		[['identifier.qualified', 'statement.block'], true]
	] as const)('reads a structure without $path as the member\'s decided path, switching only among others: %j', async (viewed, switched) => {
		const { text, diagnostics } = await runPinned('portableBuild', {
			grammar: 'python',
			api: 'PythonAPI',
			map: 'PythonMap',
			imports: { vocabulary: '@sittir/types/vocabulary', api: '../api.js', map: './map.js' },
			table: {
				builders: { functionDefinition: 'config', block: 'nullary', dottedName: 'nullary' },
				paths: {
					'declaration.function': { root: true, arms: [{ kind: 1, builder: 'functionDefinition', when: [], members: [{ name: 'body', steps: [{ key: 'body' }], multiple: false, seats: [{ at: [1, 'body'], kinds: [7, 8] }] }], presets: [], flags: {} }] },
					'statement.block': { root: false, arms: [{ kind: 7, builder: 'block', when: [], members: [], presets: [], flags: {} }] },
					'identifier.qualified': { root: false, arms: [{ kind: 8, builder: 'dottedName', when: [], members: [], presets: [], flags: {} }] }
				}
			},
			members: { 'declaration.function': { body: { paths: [...viewed], texts: [], unmapped: [], string: false, optional: false } } },
			viewed: [...viewed],
			textPaths: [],
			textInputs: [],
			textValues: [],
			holes: [],
			decided: { 'declaration.function': { body: 'statement.block' } }
		});
		expect(diagnostics).toEqual([]);
		expect(text).toContain('const declaration_function$1_body = (');
		expect(text).toContain("PathInput<PythonMap, 'statement.block'>");
		expect(text).toContain('return statement_block$7(value);');
		expect(text.includes('switch (value.$path)')).toBe(switched);
		expect(text.includes('case undefined:')).toBe(switched);
	}, 60_000);
});
