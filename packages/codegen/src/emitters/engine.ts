/**
 * Emits a thin per-grammar `engine.ts` wrapper that delegates to
 * `createNativeEngine` from `@sittir/common/engine`. The JS-engine fallback
 * has been removed — native is the only supported backend.
 */

export interface EmitEngineConfig {
	grammar: string;
	/** The grammar's root kind interface name (e.g. `SourceFile`) — types
	 *  `createEngine`'s diagnostics so `parseAndRead(...).root` needs no cast. */
	rootTypeName: string;
	/** The `wrap.ts` alias for the root kind's wrapped surface (e.g.
	 *  `SourceFileTree`) — `parse()`'s return type. Emitted by the wrap
	 *  emitter from the same table that types `wrapNode`. */
	rootTreeTypeName: string;
}

export function emitEngine(config: EmitEngineConfig): string {
	const { grammar, rootTypeName, rootTreeTypeName } = config;
	return `// Auto-generated by @sittir/codegen — do not edit
/**
 * Grammar-specific engine factory for @sittir/${grammar}.
 *
 * Thin wrapper — native binding stays in @sittir/common/engine. Native-only:
 * there is no JS-engine fallback.
 */
import {
	createNativeEngine,
	type SittirEngineLike,
	type EngineOptions
} from '@sittir/common/engine';
import { KIND_NAMES, type ${rootTypeName} } from './types.js';
import type { NodeDataOf } from '@sittir/types';
import { wrapNode, type ${rootTreeTypeName} } from './wrap.js';
import { getActiveBackend } from './backend.js';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));

/** The reader's raw root: the root kind's DATA projection — its \`$type\`
 *  and \`_<slot>\` storage, whose children are reader stubs. Accessor
 *  methods live on \`wrapNode(root, tree)\`, which is what \`parse()\` returns. */
export type ${rootTypeName}Root = NodeDataOf<${rootTypeName}>;

export type { EngineOptions, ${rootTreeTypeName} };

/**
 * A grammar engine: the product \`parse()\` surface plus the shared render /
 * edit / diagnostics surface.
 */
export interface ${rootTypeName}Engine extends SittirEngineLike<${rootTypeName}Root> {
	/** Parse \`source\` and return its wrapped root. Accessors on the result
	 *  return wrapped nodes too — no caller-side \`wrapNode\` re-wrapping. */
	parse(source: string): ${rootTreeTypeName};
}

/**
 * Create a grammar-specific engine instance.
 *
 * Native-only — throws if the native backend is unavailable rather than
 * silently falling back to a JS engine.
 *
 * @param options - Engine configuration (format, etc.)
 * @returns An engine implementing ${rootTypeName}Engine.
 */
export function createEngine(options?: EngineOptions): ${rootTypeName}Engine {
	const result = createNativeEngine<${rootTypeName}Root>(
		{
			templatesPath: join(__dirname, '..', 'templates'),
			kindNames: KIND_NAMES,
			getActiveBackend,
		},
		options
	);
	if (!result.engine) {
		throw new Error(\`createEngine: native engine unavailable (no JS-engine fallback): \${result.reason}\`);
	}
	const engine = result.engine;
	return {
		...engine,
		parse(source: string): ${rootTreeTypeName} {
			const { root, tree } = engine.diagnostics.parseAndRead(source);
			return wrapNode(root, tree);
		},
	};
}
`;
}
