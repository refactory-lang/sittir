import { grammarTypePrefix, languageApiName } from '../grammars.ts';

export interface EmitEngineConfig {
	grammar: string;
	rootTypeName: string;
	rootTreeTypeName: string;
}

export function emitRenderEngine(config: EmitEngineConfig): string {
	const { grammar, rootTypeName } = config;
	return `// Auto-generated by @sittir/codegen — do not edit
/**
 * Render-only engine for @sittir/${grammar}.
 *
 * Renders and edits node DATA. It imports no
 * wrapper, which is what keeps the module graph acyclic: constructed nodes
 * carry \`$render()\`, so \`factories -> utils -> boundary\` reaches this
 * module, and a \`parse()\` surface here would pull \`wrap.js\` and close the
 * loop back onto \`factories.js\`. Parsing lives in \`api.ts\` (the \`wrap\` hook) because
 * parsing is the half that needs the wrapper.
 *
 * Native-only — there is no JS-engine fallback.
 */
import { createNativeEngine, type SittirEngine } from '@sittir/common/engine';
import { KIND_NAMES, type ${rootTypeName} } from './types.js';
import type { IndentChar, Options } from './options.js';
import type { IndentOption, NativeEngineOptions, NodeDataOf } from '@sittir/types';
import { getActiveBackend } from './backend.js';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));

/** The reader's raw root: the root kind's DATA projection — its \`$type\`
 *  and \`_<slot>\` storage, whose children are reader stubs. */
export type ${rootTypeName}Root = NodeDataOf<${rootTypeName}>;

/**
 * Create the render / edit half of the engine.
 *
 * Throws if the native backend is unavailable rather than silently falling
 * back to a JS engine.
 */
export function createRenderEngine<const I extends string = string>(
	options?: NativeEngineOptions<Options & IndentOption<I, IndentChar>>
): SittirEngine<${rootTypeName}Root, Options, IndentChar> {
	const result = createNativeEngine<${rootTypeName}Root, Options, IndentChar>(
		{
			templatesPath: join(__dirname, '..', 'templates'),
			kindNames: KIND_NAMES,
			getActiveBackend,
		},
		options
	);
	if (!result.engine) {
		throw new Error(\`native engine unavailable (no JS-engine fallback): \${result.reason}\`);
	}
	return result.engine;
}
`;
}

export function grammarTypeMapName(grammar: string): string {
	return `${grammarTypePrefix(grammar)}TypeMap`;
}

export function emitApi(config: EmitEngineConfig): string {
	const { grammar, rootTypeName, rootTreeTypeName } = config;
	const api = languageApiName(grammar);
	return `// Auto-generated by @sittir/codegen — do not edit
import type { IndentOption, KindTypes, LanguageAPI, LanguageHooks } from '@sittir/types';
import type { TreeHandle } from '@sittir/common/utils';
import { nativeLanguageEngine, type ParsedRoot } from '@sittir/common/engine';
import { ir } from './ir.js';
import { is } from './is.js';
import { TSKindId, type FixedTextKindId, type IrKeyOf, type NamespaceMap, type ${grammarTypePrefix(grammar)}Node } from './types.js';
import type { IndentChar, Options } from './options.js';
import { methodsEngine } from './utils.js';
import { createRenderEngine, type ${rootTypeName}Root } from './render-engine.js';
import { wrapNode, type ${rootTreeTypeName} } from './wrap.js';

export interface ${api} extends LanguageAPI {
	readonly name: '${grammar}';
	readonly build: typeof ir;
	readonly is: typeof is;
	readonly kinds: typeof TSKindId;
	readonly types: KindTypes<IrKeyOf, NamespaceMap>;
	readonly root: ${rootTreeTypeName};
	readonly node: ${grammarTypePrefix(grammar)}Node;
	readonly fixedTextKindId: FixedTextKindId;
	readonly options: Options & IndentOption<string, IndentChar>;
	readonly indentChar: IndentChar;
}

export const hooks: LanguageHooks<${api}> = {
	name: '${grammar}',
	build: ir,
	is,
	kinds: TSKindId,
	trivia: methodsEngine.trivia,
	createNative: (options) => nativeLanguageEngine<${api}, IndentChar>(createRenderEngine(options)),
	wrap: (root, tree) => wrapNode(root as ${rootTypeName}Root & ParsedRoot, tree as TreeHandle)
};
`;
}
