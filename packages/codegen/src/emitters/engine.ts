export interface EmitEngineConfig {
	grammar: string;
	rootTypeName: string;
	rootTreeTypeName: string;
}

export function emitRenderEngine(config: EmitEngineConfig): string {
	const { grammar, rootTypeName } = config;
	return `// Auto-generated by @sittir/codegen — do not edit
/**
 * Render-only engine for @sittir/${grammar}.
 *
 * Renders and edits node DATA. It imports no
 * wrapper, which is what keeps the module graph acyclic: constructed nodes
 * carry \`$render()\`, so \`factories -> utils -> boundary\` reaches this
 * module, and a \`parse()\` surface here would pull \`wrap.js\` and close the
 * loop back onto \`factories.js\`. Parsing lives in \`engine.ts\` because
 * parsing is the half that needs the wrapper.
 *
 * Native-only — there is no JS-engine fallback.
 */
import { createNativeEngine, type SittirEngine, type EngineOptions } from '@sittir/common/engine';
import { KIND_NAMES, type ${rootTypeName} } from './types.js';
import type { Options } from './options.js';
import type { NodeDataOf } from '@sittir/types';
import { getActiveBackend } from './backend.js';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));

/** The reader's raw root: the root kind's DATA projection — its \`$type\`
 *  and \`_<slot>\` storage, whose children are reader stubs. */
export type ${rootTypeName}Root = NodeDataOf<${rootTypeName}>;

/**
 * Create the render / edit half of the engine.
 *
 * Throws if the native backend is unavailable rather than silently falling
 * back to a JS engine.
 */
export function createRenderEngine(options?: EngineOptions<Options>): SittirEngine<${rootTypeName}Root, Options> {
	const result = createNativeEngine<${rootTypeName}Root, Options>(
		{
			templatesPath: join(__dirname, '..', 'templates'),
			kindNames: KIND_NAMES,
			getActiveBackend,
		},
		options
	);
	if (!result.engine) {
		throw new Error(\`native engine unavailable (no JS-engine fallback): \${result.reason}\`);
	}
	return result.engine;
}
`;
}

export function emitEngine(config: EmitEngineConfig): string {
	const { grammar, rootTypeName, rootTreeTypeName } = config;
	return `// Auto-generated by @sittir/codegen — do not edit
/**
 * Grammar-specific engine factory for @sittir/${grammar}.
 *
 * Adds \`parse()\` — the half that needs \`wrap.js\` — on top of the
 * render-only engine. Anything that only renders should import
 * \`./render-engine.js\` directly; importing this module pulls the wrapper
 * and, through it, the factories.
 */
import type { SittirEngine, ParseEngine, EngineOptions, ParseOptions, RenderOptions } from '@sittir/common/engine';
import { createRenderEngine, type ${rootTypeName}Root } from './render-engine.js';
import { wrapNode, type ${rootTreeTypeName} } from './wrap.js';
import type { Options } from './options.js';

export type { ${rootTypeName}Root };
export type { EngineOptions, ParseOptions, RenderOptions, ${rootTreeTypeName} };

/**
 * A grammar engine: the public \`parse()\` surface plus the shared render /
 * edit surface. \`parse\` wraps what \`diagnostics.parseAndRead\` returns —
 * accessors on the result return wrapped nodes too, with children expanding
 * lazily unless \`{ deep: true }\` is passed.
 */
export interface ${rootTypeName}Engine
	extends SittirEngine<${rootTypeName}Root, Options>,
		ParseEngine<${rootTreeTypeName}> {}

/**
 * Create a grammar-specific engine instance.
 *
 * Native-only — throws if the native backend is unavailable rather than
 * silently falling back to a JS engine.
 *
 * @param options - Engine configuration (format, etc.)
 * @returns An engine implementing ${rootTypeName}Engine.
 */
export function createEngine(options?: EngineOptions<Options>): ${rootTypeName}Engine {
	const engine = createRenderEngine(options);
	return {
		...engine,
		parse(source: string, options?: ParseOptions): ${rootTreeTypeName} {
			const { root, tree } = engine.diagnostics.parseAndRead(source, options);
			return wrapNode(root, tree);
		},
	};
}
`;
}
