import { grammarTypePrefix, languageApiName } from '../grammars.ts';
import { spelledTriviaTable } from '../compiler/model/trivia.ts';
import type { NodeMap } from '../compiler/types.ts';
import { ownTextLeaf } from './shared.ts';

export interface EmitEngineConfig {
	grammar: string;
	rootTypeName: string;
	rootTreeTypeName: string;
	commentCoercer?: string;
	spelledTrivia?: readonly SpelledTriviaBuilder[];
}

export interface SpelledTriviaBuilder {
	readonly open: string;
	readonly close: string;
	readonly module: 'raw' | 'coerce';
	readonly builder: string;
	readonly spelledType?: string;
}

export function spelledTriviaBuilders(nodeMap: NodeMap): SpelledTriviaBuilder[] {
	const table = spelledTriviaTable(nodeMap);
	if (table === undefined || 'reason' in table) return [];
	return table.forms.flatMap((form) => {
		const node = nodeMap.nodes.get(form.kind)!;
		const leaf = form.opens.length === 1 && form.closes.length === 1 ? ownTextLeaf(node) : undefined;
		const builder: Pick<SpelledTriviaBuilder, 'module' | 'builder' | 'spelledType'> =
			leaf === undefined
				? { module: 'coerce', builder: node.fromFunctionName! }
				: { module: 'raw', builder: node.rawFactoryName!, spelledType: leaf.spelledType };
		return form.opens.flatMap((open) => form.closes.map((close) => ({ open, close, ...builder })));
	});
}

function triviaHook(config: EmitEngineConfig): string {
	const members = [
		'...triviaFacts',
		...(config.commentCoercer === undefined ? [] : [`comment: ${config.commentCoercer}`]),
		...(config.spelledTrivia === undefined || config.spelledTrivia.length === 0
			? []
			: [
					`spelled: Object.freeze([${config.spelledTrivia
						.map(
							(form) =>
								`{ open: ${JSON.stringify(form.open)}, close: ${JSON.stringify(form.close)}, build: (text: string) => ${
									form.spelledType === undefined ? `${form.builder}(text)` : `${form.builder}(text as ${form.spelledType}, false)`
								} }`
						)
						.join(', ')}])`
				])
	];
	return members.length === 1 ? 'triviaFacts' : `Object.freeze({ ${members.join(', ')} })`;
}

function triviaImports(config: EmitEngineConfig): string {
	const names = (module: 'raw' | 'coerce'): string[] => [
		...new Set([
			...(module === 'coerce' && config.commentCoercer !== undefined ? [config.commentCoercer] : []),
			...(config.spelledTrivia ?? []).filter((form) => form.module === module).map((form) => form.builder)
		])
	];
	return (['raw', 'coerce'] as const)
		.flatMap((module) =>
			names(module).length === 0 ? [] : [`import { ${names(module).join(', ')} } from './factories/${module}.js';\n`]
		)
		.join('');
}

export function emitRenderEngine(config: EmitEngineConfig): string {
	const { grammar, rootTypeName } = config;
	return `// Auto-generated by @sittir/codegen — do not edit
/**
 * Render-only engine for @sittir/${grammar}.
 *
 * Renders and edits node DATA. It imports no
 * wrapper: a \`parse()\` surface here would pull \`wrap.js\` into every render.
 * Parsing lives in \`api.ts\` (the \`wrap\` hook) because parsing is the half that
 * needs the wrapper.
 *
 * Native-only — there is no JS-engine fallback.
 */
import { createNativeEngine, type SittirEngine } from '@sittir/common/engine';
import { KIND_NAMES, type ${rootTypeName} } from './types.js';
import type { IndentChar, Options } from './options.js';
import type { IndentOption, NativeEngineOptions, UntypedNodeOf } from '@sittir/types';
import { getActiveBackend } from './backend.js';
import { triviaFacts } from './utils.js';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));

/** The reader's raw root: the root kind's DATA projection — its \`$type\`
 *  and \`_<slot>\` storage, whose children are reader stubs. */
export type ${rootTypeName}Root = UntypedNodeOf<${rootTypeName}>;

/**
 * Create the render / edit half of the engine.
 *
 * Throws if the native backend is unavailable rather than silently falling
 * back to a JS engine.
 */
export function createRenderEngine<const I extends string = string>(
	options?: NativeEngineOptions<Options & IndentOption<I, IndentChar>>
): SittirEngine<${rootTypeName}Root, Options, IndentChar> {
	const result = createNativeEngine<${rootTypeName}Root, Options, IndentChar>(
		{
			templatesPath: join(__dirname, '..', 'templates'),
			kindNames: KIND_NAMES,
			rebuildWrappers: triviaFacts.rebuildWrappers,
			listKinds: triviaFacts.listKinds,
			getActiveBackend,
		},
		options
	);
	if (!result.engine) {
		throw new Error(\`native engine unavailable (no JS-engine fallback): \${result.reason}\`);
	}
	return result.engine;
}
`;
}

export function grammarTypeMapName(grammar: string): string {
	return `${grammarTypePrefix(grammar)}TypeMap`;
}

export function emitApi(config: EmitEngineConfig): string {
	const { grammar, rootTypeName, rootTreeTypeName } = config;
	const api = languageApiName(grammar);
	return `// Auto-generated by @sittir/codegen — do not edit
import type { IndentOption, KindTypes, LanguageAPI, LanguageHooks } from '@sittir/types';
import type { TreeHandle } from '@sittir/common/utils';
import { nativeLanguageEngine, type ParsedRoot } from '@sittir/common/engine';
import { ir } from './ir.js';
import { is } from './is.js';
import { TSKindId, type FixedTextKindId, type TypeKeyOf, type NamespaceMap, type ${grammarTypePrefix(grammar)}Node, type ${grammarTypeMapName(grammar)} } from './types.js';
import type { IndentChar, Options } from './options.js';
import { querySlots, triviaFacts } from './utils.js';
${triviaImports(config)}import { RENDER_MODULE_HASH } from './hash.js';
import { createRenderEngine, type ${rootTypeName}Root } from './render-engine.js';
import { wrapNode, hydrate, type ${rootTreeTypeName} } from './wrap.js';

export interface ${api} extends LanguageAPI {
	readonly name: '${grammar}';
	readonly build: typeof ir;
	readonly is: typeof is;
	readonly kinds: typeof TSKindId;
	readonly types: KindTypes<TypeKeyOf, NamespaceMap>;
	readonly root: ${rootTreeTypeName};
	readonly node: ${grammarTypePrefix(grammar)}Node;
	readonly fixedTextKindId: FixedTextKindId;
	readonly options: Options & IndentOption<string, IndentChar>;
	readonly indentChar: IndentChar;
	readonly empty: ${grammarTypeMapName(grammar)}['empty'];
}

export const hooks: LanguageHooks<${api}> = Object.freeze<LanguageHooks<${api}>>({
	name: '${grammar}',
	renderModuleHash: RENDER_MODULE_HASH,
	build: ir,
	is,
	kinds: TSKindId,
	trivia: ${triviaHook(config)},
	querySlots,
	createNative: (options) => nativeLanguageEngine<${api}, IndentChar>(createRenderEngine(options)),
	wrap: (root, tree) => wrapNode(root as ${rootTypeName}Root & ParsedRoot, tree as TreeHandle),
	hydrate: (node, tree) => hydrate(node, tree as TreeHandle)
});
`;
}
