
export const BUILDER_SURFACES = ['loose', 'strict'] as const;
export type BuilderSurface = (typeof BUILDER_SURFACES)[number];

export const BUILDER_TABLES = [
	{ mode: 'default', surface: 'loose', alias: 'looseTable' },
	{ mode: 'strict', surface: 'strict', alias: 'strictTable' }
] as const satisfies readonly { readonly mode: string; readonly surface: BuilderSurface; readonly alias: string }[];

export function irModuleOf(surface: BuilderSurface): string {
	return surface === 'loose' ? 'ir' : 'ir-strict';
}

export const GENERATED_HEADER = '// Auto-generated by @sittir/codegen — do not edit';

const IMPORT_BINDERS = /^import\s+(?:type\s+)?(?:\*\s+as\s+(\w+)|\{([^}]*)\})\s+from/;

function importIsUsed(importLine: string, body: string): boolean {
	const m = IMPORT_BINDERS.exec(importLine);
	if (m === null) return true;
	const namespaceBinder = m[1];
	if (namespaceBinder !== undefined) return new RegExp(`\\b${namespaceBinder}\\.`).test(body);
	const named = (m[2] ?? '').split(',').map(
		(n) =>
			n
				.trim()
				.split(/\s+as\s+/)
				.pop()
				?.trim() ?? ''
	);
	return named.some((n) => n.length > 0 && new RegExp(`\\b${n}\\b`).test(body));
}

export function usedImports(imports: readonly string[], body: readonly string[]): string[] {
	const source = body.join('\n');
	return imports.filter((line) => importIsUsed(line, source));
}

export interface Ref {
	readonly value: string;
	readonly type: string;
	readonly local?: string;
	readonly members?: ReadonlyMap<string, Ref>;
	readonly spreads?: readonly Ref[];
}

export type Member = { readonly key: string; readonly ref: Ref } | { readonly spread: Ref };

export const TABLE_PARAM = '$table';
export const TABLE_TYPE = 'Table';
export const TABLE_ACCESS = '$at';
export const ROUTES_TYPE = 'Routes';
export const IR_TYPE = 'Ir';
export const ANY_TABLE_TYPE = 'AnyTable';

export function tableRef(key: string): Ref {
	return { value: `${TABLE_ACCESS}('${key}')`, type: `${TABLE_TYPE}['${key}']` };
}

export function moduleRef(namespace: string, name: string): Ref {
	return { value: `${namespace}.${name}`, type: `typeof ${namespace}.${name}` };
}

export function routesType(steps: readonly string[]): string {
	return `${ROUTES_TYPE}<${TABLE_TYPE}>${steps.map((step) => `['${step}']`).join('')}`;
}

export function localRef(name: string): Ref {
	return { value: name, type: routesType([name]), local: name };
}

export function memberAt(locals: ReadonlyMap<string, Ref>, ref: Ref, steps: readonly string[]): Ref | undefined {
	if (steps.length === 0) return ref;
	if (ref.members === undefined && ref.spreads === undefined) {
		const base = ref.local === undefined ? undefined : locals.get(ref.local);
		return base === undefined || base === ref ? undefined : memberAt(locals, base, steps);
	}
	const [head, ...rest] = steps as [string, ...string[]];
	const next = ref.members?.get(head) ?? ref.spreads?.map((spread) => memberAt(locals, spread, [head])).find((found) => found !== undefined);
	return next === undefined ? undefined : memberAt(locals, next, rest);
}

function propertyKey(key: string): string {
	return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

export function objectOf(members: readonly Member[]): Ref {
	const values = members.map((member) => ('spread' in member ? `...${member.spread.value}` : `${propertyKey(member.key)}: ${member.ref.value}`));
	const props = members.flatMap((member) => ('spread' in member ? [] : [`readonly ${propertyKey(member.key)}: ${member.ref.type}`]));
	const types = [...(props.length === 0 ? [] : [`{ ${props.join('; ')} }`]), ...members.flatMap((member) => ('spread' in member ? [member.spread.type] : []))];
	return { value: `{ ${values.join(', ')} } as const`, type: types.length === 0 ? '{}' : types.join(' & ') };
}

export function withMembers(callable: Ref | undefined, owned: boolean, members: readonly Member[]): Ref {
	if (callable !== undefined && members.length === 0) return callable;
	const object = objectOf(members);
	const tree = {
		members: new Map(members.flatMap((member): [string, Ref][] => ('spread' in member ? [] : [[member.key, member.ref]]))),
		spreads: members.flatMap((member) => ('spread' in member ? [member.spread] : []))
	};
	if (callable === undefined) return { value: `Object.freeze(${object.value})`, type: object.type, ...tree };
	return {
		value: `Object.freeze(Object.assign(${owned ? callable.value : `delegate(${callable.value})`}, ${object.value}))`,
		type: `${callable.type} & ${object.type}`,
		...tree
	};
}
