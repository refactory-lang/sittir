import type { NodeMap } from '../../compiler/types.ts';
import type { GeneratedIdTables } from '../../dsl/symbol-table.ts';
import type { AssembledNode } from '../../compiler/model/node-map.ts';
import { bundleKeyedNodes, flattenedVariantParents, ownTextKeyedNodes, type IrKeyedNode } from '../../compiler/model/ir-surface.ts';
import { collectCatalogKinds, collectKindEntries } from '../kind-discriminant.ts';
import { builtTypeSurfaceOf } from '../factories.ts';

export const OVERLAY_CHAIN = ['refines', 'polymorphs', 'supertypes'] as const;
export type OverlayName = (typeof OVERLAY_CHAIN)[number];

export function overlayImportPath(index: number): string {
	return index === 0 ? '../bundle.js' : `./${OVERLAY_CHAIN[index - 1]}.js`;
}

const HEADER = '// Auto-generated by @sittir/codegen — do not edit';

const IMPORT_BINDERS = /^import\s+(?:type\s+)?(?:\*\s+as\s+(\w+)|\{([^}]*)\})\s+from/;

function importIsUsed(importLine: string, body: string): boolean {
	const m = IMPORT_BINDERS.exec(importLine);
	if (m === null) return true;
	const namespaceBinder = m[1];
	if (namespaceBinder !== undefined) return new RegExp(`\\b${namespaceBinder}\\.`).test(body);
	const named = (m[2] ?? '').split(',').map(
		(n) =>
			n
				.trim()
				.split(/\s+as\s+/)
				.pop()
				?.trim() ?? ''
	);
	return named.some((n) => n.length > 0 && new RegExp(`\\b${n}\\b`).test(body));
}

export function overlayFrame(
	importPath: string,
	body: readonly string[],
	extraImports: readonly string[] = []
): string[] {
	const source = body.join('\n');
	const imports = [`import * as B from '${importPath}';`, ...extraImports].filter((line) => importIsUsed(line, source));
	return [HEADER, ...imports, `export * from '${importPath}';`, ''];
}

export function bundleExpr(strict: string, coerce: string | undefined, key: string, max: number | undefined): string {
	const stamp = max === undefined ? '' : `, { key: ${JSON.stringify(key)}, max: ${max} }`;
	return `bundle(${strict}, ${coerce ?? 'undefined'}${stamp})`;
}

export interface BundleEntry {
	readonly key: string;
	readonly exportName: string;
	readonly node: AssembledNode;
	readonly maxArgs: number | undefined;
}

export function bundleEntries(nodeMap: NodeMap, generatedIdTables?: GeneratedIdTables): BundleEntry[] {
	return withMaxArgs(bundleKeyedNodes(nodeMap, generatedIdTables), nodeMap, generatedIdTables);
}

export function ownTextEntries(nodeMap: NodeMap, generatedIdTables?: GeneratedIdTables): BundleEntry[] {
	return withMaxArgs(ownTextKeyedNodes(nodeMap, generatedIdTables), nodeMap, generatedIdTables);
}

function withMaxArgs(entries: readonly IrKeyedNode[], nodeMap: NodeMap, generatedIdTables?: GeneratedIdTables): BundleEntry[] {
	const kindEntries = generatedIdTables
		? collectKindEntries(collectCatalogKinds(generatedIdTables), nodeMap, generatedIdTables)
		: undefined;
	return entries.map((entry) => ({ ...entry, maxArgs: builtTypeSurfaceOf(entry.node, nodeMap, kindEntries)?.maxArgs }));
}

export function emitBundleModule(config: { nodeMap: NodeMap; generatedIdTables?: GeneratedIdTables }): string {
	const lines: string[] = [
		HEADER,
		"import * as F from './raw.js';",
		"import * as C from './coerce.js';",
		"import { bundle } from '@sittir/common/utils';",
		"export * from './raw.js';",
		"export * from './coerce.js';",
		''
	];
	for (const { exportName, node, maxArgs } of bundleEntries(config.nodeMap, config.generatedIdTables)) {
		lines.push(`export const ${exportName} = ${bundleExpr(`F.${node.rawFactoryName}`, `C.${node.fromFunctionName}`, exportName, maxArgs)};`);
	}
	lines.push('');
	return lines.join('\n');
}

export function emitFactoriesIndex(
	head: OverlayName,
	config: { nodeMap: NodeMap; generatedIdTables?: GeneratedIdTables }
): string {
	const source = `./overlays/${head}.js`;
	const lines: string[] = [
		HEADER,
		`import * as O from '${source}';`,
		"import type { Hoisted } from '@sittir/types';",
		"import { hoistAs } from '@sittir/common/utils';",
		`export * from '${source}';`,
		''
	];
	for (const { exportName } of bundleEntries(config.nodeMap, config.generatedIdTables)) {
		lines.push(`export const ${exportName}: Hoisted<typeof O.${exportName}> = hoistAs<typeof O.${exportName}>(O.${exportName});`);
	}
	for (const { key } of flattenedVariantParents(config.nodeMap, config.generatedIdTables)) {
		lines.push(`export const ${key}: Hoisted<typeof O.${key}> = hoistAs<typeof O.${key}>(O.${key});`);
	}
	lines.push('');
	return lines.join('\n');
}
