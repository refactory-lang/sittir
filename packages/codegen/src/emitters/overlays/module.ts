import type { NodeMap } from '../../compiler/types.ts';
import type { GeneratedIdTables } from '../../compiler/generated-metadata.ts';
import {
	AbstractAssembledCompound,
	AssembledList,
	FACTORY_NAME_RESERVED,
	type AssembledNode
} from '../../compiler/model/node-map.ts';
import { collectCatalogKinds, collectKindEntries, hasCatalogEntry } from '../kind-discriminant.ts';
import { camelCase } from '../refine-emit.ts';
import { classifyFromEmission, isValidIdent } from '../shared.ts';

export const OVERLAY_CHAIN = ['refines', 'polymorphs', 'supertypes'] as const;
export type OverlayName = (typeof OVERLAY_CHAIN)[number];

export function overlayImportPath(index: number): string {
	return index === 0 ? '../bundle.js' : `./${OVERLAY_CHAIN[index - 1]}.js`;
}

const HEADER = '// Auto-generated by @sittir/codegen — do not edit';

const IMPORT_BINDERS = /^import\s+(?:type\s+)?(?:\*\s+as\s+(\w+)|\{([^}]*)\})\s+from/;

function importIsUsed(importLine: string, body: string): boolean {
	const m = IMPORT_BINDERS.exec(importLine);
	if (m === null) return true;
	const namespaceBinder = m[1];
	if (namespaceBinder !== undefined) return new RegExp(`\\b${namespaceBinder}\\.`).test(body);
	const named = (m[2] ?? '').split(',').map(
		(n) =>
			n
				.trim()
				.split(/\s+as\s+/)
				.pop()
				?.trim() ?? ''
	);
	return named.some((n) => n.length > 0 && new RegExp(`\\b${n}\\b`).test(body));
}

export function overlayFrame(
	importPath: string,
	body: readonly string[],
	extraImports: readonly string[] = []
): string[] {
	const source = body.join('\n');
	const imports = [`import * as B from '${importPath}';`, ...extraImports].filter((line) => importIsUsed(line, source));
	return [HEADER, ...imports, `export * from '${importPath}';`, ''];
}

export interface BundleEntry {
	readonly key: string;
	readonly exportName: string;
	readonly node: AssembledNode;
}

export function bundleEntries(nodeMap: NodeMap, generatedIdTables?: GeneratedIdTables): BundleEntry[] {
	const kindEntries = generatedIdTables
		? collectKindEntries(collectCatalogKinds(generatedIdTables), nodeMap, generatedIdTables)
		: undefined;
	const used = new Set<string>();
	const out: BundleEntry[] = [];
	for (const [kind, node] of nodeMap.nodes) {
		if (node.factoryInline) continue;
		if (!node.rawFactoryName || !node.fromFunctionName) continue;
		if (!(node instanceof AbstractAssembledCompound) && !(node instanceof AssembledList)) continue;
		if (node instanceof AbstractAssembledCompound && !(node instanceof AssembledList) && node.hoisted) continue;
		if (kindEntries && !hasCatalogEntry(kindEntries, kind)) continue;
		if (classifyFromEmission(kind, node, { nodeMap, kindEntries }) !== 'emit') continue;
		const key = node.irKey ?? camelCase(kind);
		if (!isValidIdent(key) || used.has(key)) continue;
		used.add(key);
		out.push({ key, exportName: FACTORY_NAME_RESERVED.has(key) ? `${key}_` : key, node });
	}
	return out;
}

export function emitBundleModule(config: { nodeMap: NodeMap; generatedIdTables?: GeneratedIdTables }): string {
	const lines: string[] = [
		HEADER,
		"import * as F from './raw.js';",
		"import * as C from './coerce.js';",
		"import { bundle } from '../utils.js';",
		"export * from './raw.js';",
		"export * from './coerce.js';",
		''
	];
	for (const { exportName, node } of bundleEntries(config.nodeMap, config.generatedIdTables)) {
		lines.push(`export const ${exportName} = bundle(F.${node.rawFactoryName}, C.${node.fromFunctionName});`);
	}
	lines.push('');
	return lines.join('\n');
}

export function emitFactoriesIndex(
	head: OverlayName,
	config: { nodeMap: NodeMap; generatedIdTables?: GeneratedIdTables }
): string {
	const source = `./overlays/${head}.js`;
	const lines: string[] = [
		HEADER,
		`import * as O from '${source}';`,
		"import { hoist, type Hoisted } from '../utils.js';",
		`export * from '${source}';`,
		''
	];
	for (const { exportName } of bundleEntries(config.nodeMap, config.generatedIdTables)) {
		lines.push(`export const ${exportName}: Hoisted<typeof O.${exportName}> = hoist(O.${exportName});`);
	}
	lines.push('');
	return lines.join('\n');
}
