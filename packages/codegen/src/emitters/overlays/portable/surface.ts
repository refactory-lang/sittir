import type { PortableCondition, QueryPlan } from '@sittir/types';
import { portablePathHasFacts } from '@sittir/common/engine';
import { WILDCARD } from '../../../bindings/facts.ts';
import type { GrammarRoutes, ReadEntry } from '../../../bindings/routes.ts';
import type { SlotFlag } from './flags.ts';
import { descendants, namespaceTree, type NamespaceNode } from './namespaces.ts';

export interface PortableSurfaceConfig {
	readonly routes: GrammarRoutes;
	readonly readTest: (entry: ReadEntry) => readonly PortableCondition[];
	readonly kindIdOf: (kind: string) => string;
	readonly fixedText: readonly (readonly [kindId: string, text: string])[];
	readonly flags: readonly (readonly [kindId: string, plans: ReadonlyMap<string, QueryPlan | null>])[];
	readonly flagTypes: readonly (readonly [typeName: string, flags: readonly string[]])[];
	readonly slotFlags: readonly (readonly [kindId: number, slots: ReadonlyMap<string, ReadonlyMap<string, SlotFlag>>])[];
	readonly slotFlagTypes: readonly (readonly [typeName: string, slots: readonly (readonly [accessor: string, flags: readonly string[]])[]])[];
}

const q = (text: string): string => JSON.stringify(text);

export function emitPortableSurface({ routes, readTest, kindIdOf, fixedText, flags, flagTypes, slotFlags, slotFlagTypes }: PortableSurfaceConfig): string {
	const root = namespaceTree(routes.readEntries);
	const nodes = descendants(root);
	const byPath = new Map([root, ...nodes].map((n) => [n.path, n]));
	const braces = (parts: readonly string[]): string => (parts.length === 0 ? '{}' : `{ ${parts.join('; ')} }`);
	const members = (under: string, at: string): string[] =>
		[...byPath.get(under)!.children].map(([name, child]) => `readonly ${q(name)}: ${at}[${q(child.path)}]`);
	const reached = (kind: string): readonly ReadEntry[] | undefined => {
		const read = routes.readEntries.get(kind) ?? [];
		const last = read.findIndex((entry) => entry.claim.within.length === 0 && readTest(entry).length === 0);
		return last < 0 ? undefined : read.slice(0, last + 1);
	};
	const exact = (n: NamespaceNode): boolean =>
		n.kinds.every((kind) => reached(kind)?.every((entry) => portablePathHasFacts(n.path, entry.vocab)) ?? false);
	const entries = [...routes.readEntries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
	const entryRecord = (entry: ReadEntry): string => {
		const within = entry.claim.within.map((kind) => (kind === WILDCARD ? 'null' : kindIdOf(kind)));
		return `{ path: ${q(entry.vocab)}, within: [${within.join(', ')}], test: ${JSON.stringify(readTest(entry))} }`;
	};
	const idsOf = (kinds: readonly string[]): string[] => [...new Set(kinds.map(kindIdOf))];
	const recordsById = new Map<string, string[]>();
	for (const [kind, read] of entries) {
		const id = kindIdOf(kind);
		const records = recordsById.get(id) ?? recordsById.set(id, []).get(id)!;
		for (const record of read.map(entryRecord)) if (!records.includes(record)) records.push(record);
	}
	return [
		'// Auto-generated by @sittir/codegen — do not edit',
		'',
		"import type { PortableGuard, PortableRows, PortableTable, QueryFlags, QuerySlotFlags } from '@sittir/types';",
		"import { TSKindId } from './kinds.js';",
		"import { querySlots } from './utils.js';",
		'',
		'export interface PortableIds {',
		...nodes.map((n) => `\t${q(n.path)}: ${idsOf(n.kinds).join(' | ')};`),
		'}',
		'',
		'export interface PortableKindsAt {',
		...nodes.map((n) => `\t${q(n.path)}: ${braces([`readonly $ids: readonly PortableIds[${q(n.path)}][]`, ...members(n.path, 'PortableKindsAt')])};`),
		'}',
		'',
		'export interface PortableIsAt {',
		...nodes.map((n) => `\t${q(n.path)}: PortableGuard<PortableIds[${q(n.path)}]> & ${braces(members(n.path, 'PortableIsAt'))};`),
		'}',
		'',
		`export interface PortableKinds ${braces(members('', 'PortableKindsAt'))}`,
		'',
		`export interface PortableIs ${braces(members('', 'PortableIsAt'))}`,
		'',
		'const table: PortableTable = {',
		'\tpaths: {',
		...nodes.map((n) => `\t\t${q(n.path)}: { ids: [${idsOf(n.kinds).join(', ')}], exact: ${exact(n)} },`),
		'\t},',
		'\tentries: {',
		...[...recordsById].map(([id, records]) => `\t\t[${id}]: [${records.join(', ')}],`),
		'\t},',
		`\tfixedText: { ${fixedText.map(([id, text]) => `[${id}]: ${q(text)}`).join(', ')} },`,
		'};',
		'',
		'export const rows: PortableRows = Object.freeze({ table, querySlots });',
		'',
		'export const queryFlags: QueryFlags = Object.freeze({',
		...flags.map(([id, plans]) => `\t[${id}]: ${JSON.stringify(Object.fromEntries(plans))},`),
		'} satisfies QueryFlags);',
		'',
		'export const querySlotFlags: QuerySlotFlags = Object.freeze({',
		...slotFlags.map(([id, slots]) => `\t${id}: ${JSON.stringify(Object.fromEntries([...slots].map(([accessor, held]) => [accessor, Object.fromEntries(held)])))},`),
		'} satisfies QuerySlotFlags);',
		...(flagTypes.length === 0 && slotFlagTypes.length === 0
			? []
			: [
					'',
					"declare module './types.js' {",
					...flagTypes.flatMap(([typeName, names]) => [`\tinterface ${typeName} {`, `\t\treadonly __flags__?: ${names.map(q).join(' | ')};`, '\t}']),
					...slotFlagTypes.flatMap(([typeName, slots]) => [
						`\tinterface ${typeName} {`,
						`\t\treadonly __slotFlags__?: { ${slots.map(([accessor, names]) => `readonly ${q(accessor)}: ${names.map(q).join(' | ')}`).join('; ')} };`,
						'\t}'
					]),
					'}'
				]),
		''
	].join('\n');
}
