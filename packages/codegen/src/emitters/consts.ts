import type { NodeMap } from '../compiler/types.ts';
import type { AssembledNode, AssembledNonterminal } from '../compiler/model/node-map.ts';
import {
	AbstractAssembledCompound,
	AssembledList,
	AssembledPattern,
	AssembledEnum,
	AssembledKeyword,
	AssembledToken
} from '../compiler/model/node-map.ts';
import type { GeneratedIdEntry, GeneratedIdTable, GeneratedIdTables } from '../compiler/generated-metadata.ts';
import { keywordPresenceKind, keywordPresenceValues, keywordPresenceIsNonEmptyRepeat, escForSource } from './shared.ts';
import { collectCatalogKinds } from './kind-discriminant.ts';

export interface EmitConstsConfig {
	grammar: string;
	nodeMap: NodeMap;
	generatedIdTables?: GeneratedIdTables;
}

export function emitConsts(config: EmitConstsConfig): string {
	const { nodeMap, generatedIdTables } = config;

	const nodeKinds: string[] = [];
	const leafKinds: string[] = [];
	const keywords: string[] = [];
	const operators: string[] = [];
	const enumEntries: { kind: string; values: string[] }[] = [];

	for (const [kind, node] of nodeMap.nodes) {
		if ((node instanceof AbstractAssembledCompound && !node.hoisted) || node instanceof AssembledList) {
			nodeKinds.push(kind);
		} else if (node instanceof AssembledPattern) {
			leafKinds.push(kind);
		} else if (node instanceof AssembledEnum) {
			leafKinds.push(kind);
			enumEntries.push({ kind, values: node.values });
		} else if (node instanceof AssembledKeyword) {
			leafKinds.push(kind);
			keywords.push(kind);
		} else if (node instanceof AssembledToken) {
			operators.push(kind);
		}
	}

	const lines: string[] = ['// Auto-generated by @sittir/codegen — do not edit', ''];

	lines.push('/** All branch (non-leaf) node kind strings. */');
	lines.push('const NODE_KINDS = [');
	for (const kind of nodeKinds.sort()) {
		lines.push(`  '${kind}',`);
	}
	lines.push('] as const;');
	lines.push('');

	lines.push('/** All leaf/terminal node kind strings. */');
	lines.push('const LEAF_KINDS = [');
	for (const kind of leafKinds.sort()) {
		lines.push(`  '${kind}',`);
	}
	lines.push('] as const;');
	lines.push('');

	lines.push('/** All node kind strings (branch + leaf). */');
	lines.push('export const ALL_KINDS = [...NODE_KINDS, ...LEAF_KINDS] as const;');
	lines.push('');

	lines.push('/** Language keywords (alphabetic anonymous tokens). */');
	lines.push('export const KEYWORDS = [');
	for (const kw of keywords.sort()) {
		lines.push(`  '${kw}',`);
	}
	lines.push('] as const;');
	lines.push('');

	lines.push('/** Operator/punctuation tokens. */');
	lines.push('export const OPERATORS = [');
	for (const op of operators.sort()) {
		lines.push(`  ${JSON.stringify(op)},`);
	}
	lines.push('] as const;');
	lines.push('');

	lines.push('export type NodeKind = (typeof NODE_KINDS)[number];');
	lines.push('export type LeafKind = (typeof LEAF_KINDS)[number];');
	lines.push('export type AnyKind = (typeof ALL_KINDS)[number];');
	lines.push('export type Keyword = (typeof KEYWORDS)[number];');
	lines.push('export type AnyOperator = (typeof OPERATORS)[number];');
	lines.push('');

	emitTreeSitterIdConsts(lines, {
		kindIds: generatedIdTables?.kindIds,
		fieldIds: generatedIdTables?.fieldIds,
		kinds: generatedIdTables
			? collectCatalogKinds(generatedIdTables)
			: [...new Set([...nodeKinds, ...leafKinds, ...keywords, ...operators])],
		fields: collectFieldNames(nodeMap),
		sourceArtifact: generatedIdTables?.sourceArtifact
	});

	emitBitflagConstEnums(lines, nodeMap);

	const emittedValueTypes = new Set<string>();
	for (const ek of enumEntries.sort((a, b) => a.kind.localeCompare(b.kind))) {
		const constName = ek.kind.toUpperCase() + 'S';
		const typeName =
			ek.kind
				.split('_')
				.filter(Boolean)
				.map((w) => w.charAt(0).toUpperCase() + w.slice(1))
				.join('') + 'Value';

		lines.push(`/** Valid values for \`${ek.kind}\` nodes. */`);
		lines.push(`export const ${constName} = [`);
		for (const v of ek.values) {
			lines.push(`  '${escForSource(v)}',`);
		}
		lines.push('] as const;');
		if (!emittedValueTypes.has(typeName)) {
			emittedValueTypes.add(typeName);
			lines.push(`export type ${typeName} = (typeof ${constName})[number];`);
		}
		lines.push('');
	}

	return lines.join('\n');
}

interface TreeSitterIdConstConfig {
	readonly kindIds?: GeneratedIdTable;
	readonly fieldIds?: GeneratedIdTable;
	readonly kinds: readonly string[];
	readonly fields: readonly string[];
	readonly sourceArtifact?: string;
}

interface IdEnumEntry {
	readonly key: string;
	readonly id: number;
	readonly cName?: string;
	readonly memberName: string;
}

function emitTreeSitterIdConsts(lines: string[], config: TreeSitterIdConstConfig): void {
	const kindEntries = collectIdEntries(config.kinds, config.kindIds);
	const fieldEntries = collectIdEntries(config.fields, config.fieldIds);
	if (kindEntries.length === 0 && fieldEntries.length === 0) return;

	lines.push('/** Tree-sitter numeric IDs from the generated parser artifact. */');
	if (config.sourceArtifact) {
		lines.push(`export const TREE_SITTER_ID_SOURCE = ${JSON.stringify(config.sourceArtifact)};`);
	}
	lines.push('');

	emitIdMaps(lines, {
		forwardName: 'TREE_SITTER_KIND_ID_BY_KIND',
		reverseName: 'TREE_SITTER_KIND_BY_KIND_ID',
		jsonName: 'TREE_SITTER_KIND_ID_JSON',
		entries: kindEntries
	});
	lines.push('');

	emitIdEnumBlock(lines, {
		enumName: 'TSFieldId',
		forwardName: 'TREE_SITTER_FIELD_ID_BY_NAME',
		reverseName: 'TREE_SITTER_FIELD_NAME_BY_ID',
		jsonName: 'TREE_SITTER_FIELD_ID_JSON',
		recordType: 'Record<string, TSFieldId>',
		entries: fieldEntries
	});
}

function emitIdEnumBlock(
	lines: string[],
	config: {
		readonly enumName: string;
		readonly forwardName: string;
		readonly reverseName: string;
		readonly jsonName: string;
		readonly recordType: string;
		readonly entries: readonly IdEnumEntry[];
	}
): void {
	if (config.entries.length === 0) return;

	lines.push(`export const enum ${config.enumName} {`);
	for (const entry of config.entries) {
		lines.push(`  ${entry.memberName} = ${entry.id},`);
	}
	lines.push('}');
	lines.push('');

	lines.push(`export const ${config.forwardName} = {`);
	for (const entry of config.entries) {
		lines.push(`  ${JSON.stringify(entry.key)}: ${config.enumName}.${entry.memberName},`);
	}
	lines.push(`} as const satisfies ${config.recordType};`);
	lines.push('');

	lines.push(`export const ${config.reverseName} = {`);
	for (const entry of config.entries) {
		lines.push(`  [${config.enumName}.${entry.memberName}]: ${JSON.stringify(entry.key)},`);
	}
	lines.push('} as const;');
	lines.push('');

	lines.push(`export const ${config.jsonName} = [`);
	for (const entry of config.entries) {
		lines.push(
			`  { name: ${JSON.stringify(entry.key)}, id: ${entry.id}, enumName: ${JSON.stringify(entry.memberName)}, cName: ${JSON.stringify(entry.cName ?? null)} },`
		);
	}
	lines.push('] as const;');
	lines.push('');
}

function emitIdMaps(
	lines: string[],
	config: {
		readonly forwardName: string;
		readonly reverseName: string;
		readonly jsonName: string;
		readonly entries: readonly IdEnumEntry[];
	}
): void {
	if (config.entries.length === 0) return;

	lines.push(`export const ${config.forwardName} = {`);
	for (const entry of config.entries) {
		lines.push(`  ${JSON.stringify(entry.key)}: ${entry.id},`);
	}
	lines.push('} as const satisfies Record<string, number>;');
	lines.push('');

	lines.push(`export const ${config.reverseName} = {`);
	for (const entry of config.entries) {
		lines.push(`  [${entry.id}]: ${JSON.stringify(entry.key)},`);
	}
	lines.push('} as const;');
	lines.push('');

	lines.push(`export const ${config.jsonName} = [`);
	for (const entry of config.entries) {
		lines.push(
			`  { name: ${JSON.stringify(entry.key)}, id: ${entry.id}, enumName: ${JSON.stringify(entry.memberName)}, cName: ${JSON.stringify(entry.cName ?? null)} },`
		);
	}
	lines.push('] as const;');
}

function collectIdEntries(keys: readonly string[], ids: GeneratedIdTable | undefined): IdEnumEntry[] {
	const idMap = toIdMap(ids);
	const usedNames = new Map<string, string>();
	const result: IdEnumEntry[] = [];

	const keyedEntries = [...new Set(keys)]
		.map((key) => ({ key, entry: idMap.get(key) }))
		.filter((item): item is { key: string; entry: GeneratedIdEntry } => item.entry !== undefined)
		.sort(
			(a, b) =>
				(a.entry.id ?? -1) - (b.entry.id ?? -1) ||
				a.key.localeCompare(b.key) ||
				(a.entry.parser?.cSymbol ?? '').localeCompare(b.entry.parser?.cSymbol ?? '')
		);

	for (const { key, entry } of keyedEntries) {
		const cSymbol = entry.parser?.cSymbol;
		const baseName =
			cSymbol && /^[A-Za-z_]\w*$/.test(cSymbol) ? treeSitterCNameMemberName(cSymbol) : treeSitterIdMemberName(key);
		const existingKey = usedNames.get(baseName);
		const memberName = existingKey === undefined || existingKey === key ? baseName : `${baseName}_${entry.id ?? ''}`;
		usedNames.set(memberName, key);
		if (existingKey === undefined) usedNames.set(baseName, key);
		result.push({ key, id: entry.id ?? -1, cName: cSymbol, memberName });
	}

	return result;
}

function toIdMap(ids: GeneratedIdTable | undefined): Map<string, GeneratedIdEntry> {
	if (!ids) return new Map();
	const entries = ids instanceof Map ? [...ids.entries()] : Object.entries(ids);
	return new Map(entries.map(([name, entry]) => [name, typeof entry === 'number' ? { id: entry } : entry]));
}

function collectFieldNames(nodeMap: NodeMap): string[] {
	const result = new Set<string>();
	for (const [, node] of nodeMap.nodes) {
		for (const field of node.slots) result.add(field.name);
	}
	return [...result];
}

function treeSitterIdMemberName(key: string): string {
	if (key.startsWith('_')) {
		const name = pascalCaseFromSnake(key);
		return name ? `Hidden${name}` : 'Hidden';
	}
	if (/^[A-Za-z_]\w*$/.test(key)) return pascalCaseFromSnake(key);
	return bitflagMemberName(key);
}

function treeSitterCNameMemberName(cName: string): string {
	return treeSitterPascalCase(cName.replace('sym_', ''));
}

function treeSitterPascalCase(s: string): string {
	return s
		.replace(/^_+/, '')
		.split('_')
		.filter(Boolean)
		.map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
		.join('');
}

interface BitflagBinding {
	readonly kind: string;
	readonly field: AssembledNonterminal;
	readonly constName: string;
	readonly values: readonly string[];
	readonly nonEmptyRepeat: boolean;
}

function emitBitflagConstEnums(lines: string[], nodeMap: NodeMap): void {
	const bindings = collectBitflagBindings(nodeMap);
	if (bindings.length === 0) return;
	bindings.sort((a, b) => a.constName.localeCompare(b.constName));

	lines.push('// Bitflag const enums — ordered-unique literal sets per bitflag field (ADR-0012)');
	const seen = new Set<string>();
	for (const b of bindings) {
		if (seen.has(b.constName)) continue;
		seen.add(b.constName);
		lines.push(`/** Bitflag set for \`${b.kind}.${b.field.name}\`. */`);
		lines.push(`export const enum ${b.constName} {`);
		if (!b.nonEmptyRepeat) {
			lines.push('  None = 0,');
		}
		b.values.forEach((v, i) => {
			lines.push(`  ${bitflagMemberName(v)} = 1 << ${i},`);
		});
		lines.push('}');
		lines.push('');
	}
}

function collectBitflagBindings(nodeMap: NodeMap): BitflagBinding[] {
	const candidates: {
		kind: string;
		field: AssembledNonterminal;
		bare: string;
		prefixed: string;
		values: readonly string[];
		nonEmptyRepeat: boolean;
	}[] = [];
	for (const [kind, node] of nodeMap.nodes) {
		for (const f of node.slots) {
			if (keywordPresenceKind(f, nodeMap) !== 'bitflag') continue;
			const values = keywordPresenceValues(f, nodeMap);
			if (values.length < 2) continue;
			candidates.push({
				kind,
				field: f,
				bare: bitflagBareConstName(f.propertyName),
				prefixed: bitflagPrefixedConstName(kind, f.propertyName),
				values,
				nonEmptyRepeat: keywordPresenceIsNonEmptyRepeat(f)
			});
		}
	}
	const bareCounts = new Map<string, number>();
	for (const c of candidates) bareCounts.set(c.bare, (bareCounts.get(c.bare) ?? 0) + 1);
	return candidates.map((c) => ({
		kind: c.kind,
		field: c.field,
		constName: (bareCounts.get(c.bare) ?? 0) > 1 ? c.prefixed : c.bare,
		values: c.values,
		nonEmptyRepeat: c.nonEmptyRepeat
	}));
}

export function bitflagBareConstName(propertyName: string): string {
	return pascalCaseFromCamel(propertyName);
}

export function bitflagPrefixedConstName(kind: string, propertyName: string): string {
	return pascalCaseFromSnake(kind) + pascalCaseFromCamel(propertyName);
}

export function resolveBitflagConstName(
	kind: string,
	field: AssembledNonterminal,
	nodeMap: NodeMap
): string | undefined {
	if (keywordPresenceKind(field, nodeMap) !== 'bitflag') return undefined;
	const bareCounts = new Map<string, number>();
	for (const [k, n] of nodeMap.nodes) {
		for (const f of n.slots) {
			if (keywordPresenceKind(f, nodeMap) !== 'bitflag') continue;
			const bare = bitflagBareConstName(f.propertyName);
			bareCounts.set(bare, (bareCounts.get(bare) ?? 0) + 1);
			void k;
			void n;
		}
	}
	const bare = bitflagBareConstName(field.propertyName);
	return (bareCounts.get(bare) ?? 0) > 1 ? bitflagPrefixedConstName(kind, field.propertyName) : bare;
}

