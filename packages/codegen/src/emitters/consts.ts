import type { NodeMap } from '../compiler/types.ts';
import type { AssembledNonterminal } from '../compiler/model/node-map.ts';
import { AbstractAssembledCompound } from '../compiler/model/node-map.ts';
import { keywordPresenceKind, keywordPresenceValues, keywordPresenceIsNonEmptyRepeat, compareOrdinal } from './shared.ts';
import { collectInteriors } from './interior.ts';
import { kindTypeName, pascalCase } from '../compiler/model/casing.ts';

export interface EmitConstsConfig {
	grammar: string;
	nodeMap: NodeMap;
}

export function emitConsts(config: EmitConstsConfig): string {
	const { nodeMap } = config;
	const lines: string[] = ['// Auto-generated by @sittir/codegen — do not edit', ''];

	emitTokenInteriors(lines, nodeMap);
	emitInnerGaps(lines, nodeMap);
	emitBitflagConstEnums(lines, nodeMap);

	return lines.join('\n');
}

function emitInnerGaps(lines: string[], nodeMap: NodeMap): void {
	const rows = [...nodeMap.nodes]
		.flatMap(([kind, node]) =>
			node instanceof AbstractAssembledCompound && node.innerGaps.length > 0
				? [[kind, node.innerGaps.map((gap) => gap.key)] as const]
				: []
		)
		.sort(([a], [b]) => compareOrdinal(a, b));
	lines.push('/** The gaps an empty node of each kind holds inner trivia in, in render order. */');
	lines.push('export const INNER_GAPS: { readonly [kind: string]: readonly string[] } = Object.freeze({');
	for (const [kind, keys] of rows) lines.push(`  ${JSON.stringify(kind)}: Object.freeze(${JSON.stringify(keys)}),`);
	lines.push('});');
	lines.push('');
}

function emitTokenInteriors(lines: string[], nodeMap: NodeMap): void {
	const interiors = collectInteriors(nodeMap);
	if (interiors.size === 0) return;
	lines.push("import type { TokenInterior } from '@sittir/common/utils';");
	lines.push('');
	lines.push('/** Slot structure of every token whose lexed text carries literal affixes, flags or enums around its content. */');
	lines.push('export const TOKEN_INTERIORS = {');
	for (const [kind, interior] of [...interiors].sort(([a], [b]) => compareOrdinal(a, b))) {
		lines.push(`  ${JSON.stringify(kind)}: ${JSON.stringify({ regex: interior.regex, slots: interior.slots })},`);
	}
	lines.push("} as const satisfies { readonly [kind: string]: TokenInterior };");
	lines.push('');
}

interface BitflagBinding {
	readonly kind: string;
	readonly field: AssembledNonterminal;
	readonly constName: string;
	readonly values: readonly string[];
	readonly nonEmptyRepeat: boolean;
}

function emitBitflagConstEnums(lines: string[], nodeMap: NodeMap): void {
	const bindings = collectBitflagBindings(nodeMap);
	if (bindings.length === 0) return;
	bindings.sort((a, b) => compareOrdinal(a.constName, b.constName));

	lines.push('// Bitflag enums — ordered-unique literal sets per bitflag field');
	const seen = new Set<string>();
	for (const b of bindings) {
		if (seen.has(b.constName)) continue;
		seen.add(b.constName);
		lines.push(`/** Bitflag set for \`${b.kind}.${b.field.name}\`. */`);
		lines.push(`export enum ${b.constName} {`);
		if (!b.nonEmptyRepeat) {
			lines.push('  None = 0,');
		}
		b.values.forEach((v, i) => {
			lines.push(`  ${bitflagMemberName(v)} = 1 << ${i},`);
		});
		lines.push('}');
		lines.push('');
	}
}

function collectBitflagBindings(nodeMap: NodeMap): BitflagBinding[] {
	const candidates: {
		kind: string;
		field: AssembledNonterminal;
		bare: string;
		prefixed: string;
		values: readonly string[];
		nonEmptyRepeat: boolean;
	}[] = [];
	for (const [kind, node] of nodeMap.nodes) {
		for (const f of node.slots) {
			if (keywordPresenceKind(f, nodeMap) !== 'bitflag') continue;
			const values = keywordPresenceValues(f, nodeMap);
			if (values.length < 2) continue;
			candidates.push({
				kind,
				field: f,
				bare: bitflagBareConstName(f.propertyName),
				prefixed: bitflagPrefixedConstName(kind, f.propertyName),
				values,
				nonEmptyRepeat: keywordPresenceIsNonEmptyRepeat(f)
			});
		}
	}
	const bareCounts = new Map<string, number>();
	for (const c of candidates) bareCounts.set(c.bare, (bareCounts.get(c.bare) ?? 0) + 1);
	return candidates.map((c) => ({
		kind: c.kind,
		field: c.field,
		constName: (bareCounts.get(c.bare) ?? 0) > 1 ? c.prefixed : c.bare,
		values: c.values,
		nonEmptyRepeat: c.nonEmptyRepeat
	}));
}

export function bitflagBareConstName(propertyName: string): string {
	return pascalCase(propertyName);
}

export function bitflagPrefixedConstName(kind: string, propertyName: string): string {
	return kindTypeName(kind) + pascalCase(propertyName);
}

export function resolveBitflagConstName(
	kind: string,
	field: AssembledNonterminal,
	nodeMap: NodeMap
): string | undefined {
	if (keywordPresenceKind(field, nodeMap) !== 'bitflag') return undefined;
	const bareCounts = new Map<string, number>();
	for (const [k, n] of nodeMap.nodes) {
		for (const f of n.slots) {
			if (keywordPresenceKind(f, nodeMap) !== 'bitflag') continue;
			const bare = bitflagBareConstName(f.propertyName);
			bareCounts.set(bare, (bareCounts.get(bare) ?? 0) + 1);
			void k;
			void n;
		}
	}
	const bare = bitflagBareConstName(field.propertyName);
	return (bareCounts.get(bare) ?? 0) > 1 ? bitflagPrefixedConstName(kind, field.propertyName) : bare;
}

