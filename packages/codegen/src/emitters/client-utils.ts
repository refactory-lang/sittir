import type { StructureRow } from '@sittir/types';
import type { NodeMap } from '../compiler/types.ts';
import { whitespaceTrivia, type WhitespaceTrivia } from '../compiler/model/trivia.ts';
import { compareOrdinal, keywordPresenceValue, wireRoutesOf, type WireRoutes } from './shared.ts';
import { AssembledSupertype, type AssembledNonterminal } from '../compiler/model/node-map.ts';
import { grammarTypeMapName } from './engine.ts';
import { nodeSlotNumbers } from './render-module.ts';
import { layoutTriviaKindIds, listKindIds, rebuildWrapperKindIds } from './wrap.ts';

export interface EmitClientUtilsConfig {
	grammar: string;
	nodeMap: NodeMap;
	triviaKinds?: string[];
	structure?: ReadonlyMap<number, StructureRow>;
}

export function emitClientUtils(config: EmitClientUtilsConfig): string {
	const map = grammarTypeMapName(config.grammar);
	return [
		'// Auto-generated by @sittir/codegen — do not edit',
		'',
		"import type { AnyUntypedNode, QuerySlots, StructureTable, TriviaFacts } from '@sittir/types';",
		"import { bindRuntime } from '@sittir/common/utils';",
		`import { KIND_NAMES, type ${map} } from './types.js';`,
		"import { INNER_SITES } from './consts.js';",
		'',
		...emitTriviaFacts(
			whitespaceTrivia(config.nodeMap),
			config.triviaKinds ?? [],
			rebuildWrapperKindIds(config.nodeMap),
			listKindIds(config.nodeMap),
			layoutTriviaKindIds(config.nodeMap)
		),
		'',
		...emitQuerySlots(querySlotRows(config.nodeMap)),
		'',
		...emitStructure(config.structure ?? new Map()),
		'',
		`export const { isNode } = bindRuntime<${map}>();`,
		''
	].join('\n');
}

function emitTriviaFacts(
	whitespace: WhitespaceTrivia | undefined,
	triviaKinds: readonly string[],
	rebuildWrappers: readonly number[],
	listKinds: readonly number[],
	layoutKinds: readonly number[]
): string[] {
	const facts = [
		"    kindName: (type: AnyUntypedNode['$type']) => (typeof type === 'number' ? KIND_NAMES.get(type) : type)",
		`    kinds: new Set<string>(${JSON.stringify([...triviaKinds].sort(compareOrdinal))})`,
		'    innerKinds: INNER_SITES',
		`    rebuildWrappers: new Set<number>(${JSON.stringify(rebuildWrappers)})`,
		`    listKinds: new Set<number>(${JSON.stringify(listKinds)})`,
		`    layout: new Set<number>(${JSON.stringify(layoutKinds)})`,
		...(whitespace === undefined
			? []
			: [
					`    whitespace: Object.freeze({ run: /${whitespace.run.source}/${whitespace.run.flags}, kindIdByText: Object.freeze(${JSON.stringify(Object.fromEntries(whitespace.kindIdByText))}) })`
				])
	];
	return ['export const triviaFacts = Object.freeze({', facts.join(',\n'), '} satisfies TriviaFacts);'];
}

type QuerySlotRow = readonly [accessor: string, slot: number, keyword?: string];

const RECORDER_FLAG_KEY = 'is';

export function queryRoutesOf(slot: AssembledNonterminal, nodeMap: NodeMap): WireRoutes {
	return slot.fieldName === undefined ? wireRoutesOf(slot, nodeMap) : { fields: [slot.fieldName], kinds: [] };
}

export function querySlotRows(nodeMap: NodeMap): ReadonlyMap<number, readonly QuerySlotRow[]> {
	const rows = new Map<number, readonly QuerySlotRow[]>();
	for (const node of nodeMap.nodes.values()) {
		if (node.kindId === undefined || node.slots.length === 0) continue;
		const numbers = nodeSlotNumbers(node, nodeMap);
		const row = node.slots.map((slot): QuerySlotRow => {
			if (slot.propertyName === RECORDER_FLAG_KEY)
				throw new Error(`client-utils: ${node.kind}'s slot ${slot.name} is read as \`${RECORDER_FLAG_KEY}\`, which a where condition reserves for flags`);
			const number = numbers.get(slot.storageName);
			if (number === undefined) throw new Error(`client-utils: ${node.kind}'s slot ${slot.name} has no field in its node, so a query cannot number it`);
			const keyword = keywordPresenceValue(slot, nodeMap);
			return keyword === undefined ? [slot.propertyName, number] : [slot.propertyName, number, keyword];
		});
		const claimed = rows.get(node.kindId);
		if (claimed !== undefined && JSON.stringify(claimed) !== JSON.stringify(row)) {
			throw new Error(`client-utils: kind id ${node.kindId} ('${node.kind}') has two slot tables`);
		}
		rows.set(node.kindId, row);
	}
	return new Map([...rows].sort(([a], [b]) => a - b));
}

function emitStructure(structure: ReadonlyMap<number, StructureRow>): string[] {
	const entries = [...structure].sort(([a], [b]) => a - b).map(([kindId, row]) => `    ${kindId}: ${JSON.stringify(row)}`);
	return ['export const structure: StructureTable = Object.freeze({', entries.join(',\n'), '});'];
}

function emitQuerySlots(rows: ReadonlyMap<number, readonly QuerySlotRow[]>): string[] {
	const entries = [...rows].map(([kindId, row]) => `    ${kindId}: ${JSON.stringify(row)}`);
	return ['export const querySlots: QuerySlots = Object.freeze({', entries.join(',\n'), '});'];
}

export function resolveTriviaTypeNames(triviaKinds: readonly string[], nodeMap: NodeMap): string[] {
	const covered = new Set(
		triviaKinds.flatMap((kind) => {
			const node = nodeMap.nodes.get(kind);
			return node instanceof AssembledSupertype ? node.subtypeNames : [];
		})
	);
	const names = triviaKinds.flatMap((kind) => {
		const node = nodeMap.nodes.get(kind);
		return node === undefined || covered.has(kind) ? [] : [node.typeName];
	});
	return [...new Set(names)].sort();
}

export function buildTriviaNodeType(triviaTypeNames: readonly string[]): string {
	return triviaTypeNames.length > 0 ? triviaTypeNames.join(' | ') : 'AnyUntypedNode';
}
