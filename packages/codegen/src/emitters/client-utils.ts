import type { NodeMap } from '../compiler/types.ts';
import type { GeneratedIdTables } from '../compiler/generated-metadata.ts';
export interface EmitClientUtilsConfig {
	nodeMap: NodeMap;
	generatedIdTables?: GeneratedIdTables;
	triviaKinds?: string[];
}

export function emitClientUtils(config: EmitClientUtilsConfig): string {
	const triviaTypeNames = resolveTriviaTypeNames(config.triviaKinds ?? [], config.nodeMap);
	const lines: string[] = [];
	lines.push('// Auto-generated by @sittir/codegen — do not edit');
	lines.push('// Typed facade over @sittir/common/utils with grammar-local narrowing helpers');
	lines.push('');
	lines.push("import type { AnyNodeData, AnyTreeNodeOf, ByteRange, Edit } from '@sittir/types';");
	if (triviaTypeNames.length > 0) {
		lines.push(`import type { ${triviaTypeNames.join(', ')}, NamespaceMap } from './types.js';`);
	} else {
		lines.push("import type { NamespaceMap } from './types.js';");
	}
	lines.push("import { render, toEdit } from './boundary.ts';");
	lines.push(
		"import { withMethods as withCommonMethods, isNodeData as _isNodeData, isTreeNode as _isTreeNode, hasKind, coerceBooleanKeywordStorage, coerceBitflagStorage, withAccessors } from '@sittir/common/utils';"
	);
	lines.push("import type { WithMethodsEngine } from '@sittir/common/utils';");
	lines.push('');
	lines.push('export { hasKind, coerceBooleanKeywordStorage, coerceBitflagStorage, withAccessors };');
	lines.push('');
	lines.push(...emitIsNodeData());
	lines.push('');
	lines.push(...emitIsTreeNode());
	lines.push('');
	lines.push(...emitMethodsEngine());
	lines.push('');
	lines.push(...emitWithMethods(triviaTypeNames));
	lines.push('');
	lines.push(...emitNodeGuards());
	lines.push('');
	lines.push(...emitTransportHelpers());
	lines.push('');
	lines.push(...emitAttachProps());
	return lines.join('\n');
}

function emitAttachProps(): string[] {
	return [
		'export function attachProps<T extends (...args: never[]) => unknown, P extends Record<string, unknown>>(fn: T, props: P): T & P {',
		'  for (const key of Object.keys(props)) {',
		'    Object.defineProperty(fn, key, { value: props[key], writable: true, configurable: true, enumerable: true });',
		'  }',
		'  return fn as T & P;',
		'}',
		'',
		'export interface FlavorPair<S, C> { readonly strict: S; readonly coerce: C }',
		'',
		'export function bundle<S, C>(strict: S, coerce: C): FlavorPair<S, C> {',
		'  return { strict, coerce };',
		'}',
		'',
		'type AnyFlavorFn = (...args: never[]) => unknown;',
		'',
		'export type ArgsOf<F> = F extends (...args: infer P) => unknown',
		'  ? P',
		'  : F extends (...args: readonly (infer E)[]) => unknown',
		'    ? E[]',
		'    : never;',
		'',
		'export type OmitEach<T, K extends PropertyKey> = T extends unknown ? Omit<T, K> : never;',

		'',
		'export type Hoisted<B> = B extends { coerce: infer C }',
		'  ? (C extends AnyFlavorFn ? C : () => never) & { [K in keyof B]: Hoisted<B[K]> }',
		'  : B extends { strict: infer S }',
		'    ? (S extends AnyFlavorFn ? S : () => never) & { [K in keyof B]: Hoisted<B[K]> }',
		'    : B extends Record<string, unknown>',
		'      ? { [K in keyof B]: Hoisted<B[K]> }',
		'      : B;',
		'',
		'function isFlavorPair(value: unknown): value is { strict: unknown; coerce?: unknown } {',
		'  if (typeof value !== "object" || value === null) return false;',
		'  const v = value as { strict?: unknown; coerce?: unknown };',
		'  return typeof v.strict === "function" || typeof v.coerce === "function";',
		'}',
		'',
		'export function hoist<B extends { strict: unknown; coerce?: unknown }>(b: B): Hoisted<B> {',
		'  const target = (typeof b.coerce === "function" ? b.coerce : b.strict) as AnyFlavorFn;',
		'  const callable = (...args: never[]) => target(...args);',
		'  for (const [key, value] of Object.entries(b)) {',
		'    Object.defineProperty(callable, key, {',
		'      value: isFlavorPair(value) ? hoist(value) : value,',
		'      writable: true,',
		'      configurable: true,',
		'      enumerable: true',
		'    });',
		'  }',
		'  return callable as Hoisted<B>;',
		'}'
	];
}

function emitMethodsEngine(): string[] {
	return [
		'export const methodsEngine = {',
		'  render(node: AnyNodeData) { return render(node); },',
		'  toEdit(node: AnyNodeData, startOrRange: number | ByteRange, endPos?: number) { return toEdit(node, startOrRange, endPos); },',
		'} satisfies WithMethodsEngine;'
	];
}

function emitWithMethods(triviaTypeNames: readonly string[]): string[] {
	const triviaType = buildTriviaParamType(triviaTypeNames);
	return [
		'/** The methods every node carries. Named, and self-referential through',
		' *  the polymorphic `this`, because `$trivia` rebuilds the node and hands',
		' *  back the same kind. A type alias cannot name itself, so the earlier',
		' *  declaration fell back to `AnyNodeData` and lost the type at every',
		' *  `$trivia` call site. */',
		'export interface NodeMethodsOf {',
		'  $render(): string;',
		'  $toEdit(startOrRange: number | ByteRange, endPos?: number): Edit;',
		'  $replace(target: { range(): ByteRange }): Edit;',
		`  $trivia(...args: ${triviaType}[]): this;`,
		'}',
		'',
		'export function withMethods<T extends object>(',
		'  node: T,',
		'  engine: typeof methodsEngine',
		'): T & NodeMethodsOf {',
		'  // Grammar-local facade: T extends object to accept wrap.ts union-spread literals.',
		'  // Only factory/wrap output — which always satisfies AnyNodeData structurally — calls this.',
		'  return withCommonMethods(node as unknown as T & AnyNodeData, engine) as T & NodeMethodsOf;',
		'}'
	];
}

function emitIsNodeData(): string[] {
	return [
		'export function isNodeData<K extends keyof NamespaceMap>(',
		"  v: NamespaceMap[K]['Node'] | NamespaceMap[K]['Loose'] | NamespaceMap[K]['Tree']",
		"): v is Extract<NamespaceMap[K]['Node'], AnyNodeData>;",
		'export function isNodeData(v: unknown): v is AnyNodeData;',
		'export function isNodeData(v: unknown): v is AnyNodeData {',
		'  return _isNodeData(v);',
		'}'
	];
}

function emitIsTreeNode(): string[] {
	return [
		'export function isTreeNode<K extends keyof NamespaceMap>(',
		"  v: NamespaceMap[K]['Tree'] | NamespaceMap[K]['Node']",
		"): v is NamespaceMap[K]['Tree'];",
		'export function isTreeNode(v: unknown): v is AnyTreeNodeOf;',
		'export function isTreeNode(v: unknown): v is AnyTreeNodeOf {',
		'  return _isTreeNode(v);',
		'}'
	];
}

function emitNodeGuards(): string[] {
	return [
		'export function isNodeOfKind<K extends keyof NamespaceMap>(',
		'  v: unknown,',
		'  kind: K,',
		"): v is Extract<NamespaceMap[K]['Node'], AnyNodeData> {",
		'  return isNodeData(v) && v.$type === kind;',
		'}',
		'',
		'export function hasKindOf<K extends keyof NamespaceMap>(',
		'  v: object,',
		'  kind: K,',
		"): v is { kind: K } & NamespaceMap[K]['Loose'] {",
		"  return 'kind' in v && (v as Record<string, unknown>).kind === kind;",
		'}'
	];
}

function emitTransportHelpers(): string[] {
	return [
		'export function coerceMixedEnumStorage<T = unknown>(',
		'  value: unknown,',
		'  byText: readonly (readonly [string, number])[] = []',
		'): T {',
		'  if (value === undefined || value === null) return undefined as T;',
		"  if (typeof value === 'number') return value as T;",
		'  if (Array.isArray(value)) {',
		'    return value',
		'      .map((item) => coerceMixedEnumStorage(item, byText))',
		'      .filter((item) => item !== undefined) as T;',
		'  }',
		"  if (typeof value === 'string') {",
		'    const mapped = byText.find(([candidate]) => candidate === value);',
		'    return (mapped ? mapped[1] : value) as T;',
		'  }',
		'  if (isRecord(value) && typeof value.$type === "number" && byText.some(([, id]) => id === value.$type)) {',
		'    return value.$type as T;',
		'  }',
		'  return value as T;',
		'}',
		'',
		'export function coerceKindEnumStorage<T = unknown>(',
		'  value: unknown,',
		'  byText: readonly (readonly [string, number])[] = []',
		'): T {',
		'  if (value === undefined || value === null) return undefined as T;',
		"  if (typeof value === 'number') return value as T;",
		'  if (Array.isArray(value)) {',
		'    return value',
		'      .map((item) => coerceKindEnumStorage(item, byText))',
		'      .filter((item) => item !== undefined) as T;',
		'  }',
		'  const text = extractNodeText(value);',
		'  if (text !== undefined) {',
		'    const mapped = byText.find(([candidate]) => candidate === text);',
		'    if (mapped) return mapped[1] as T;',
		'  }',
		'  if (isRecord(value) && typeof value.$type === "number") return value.$type as T;',
		"  if (typeof value === 'string') {",
		'    const mapped = byText.find(([candidate]) => candidate === value);',
		'    if (mapped) return mapped[1] as T;',
		"    // The slot's own literal table is the ONLY string surface — an",
		'    // unknown string must fail here, not resolve through the global',
		"    // kind catalog into a valid-looking id outside the slot's member",
		'    // union.',
		'    throw new Error(',
		'      `kind-enum slot: ${JSON.stringify(value)} is not a valid value (expected one of: ${byText.map(([t]) => t).join(", ")})`',
		'    );',
		'  }',
		'  return value as T;',
		'}',
		'',
		'function extractNodeText(value: unknown): string | undefined {',
		"  if (typeof value === 'string') return value;",
		'  if (isNodeData(value)) {',
		"    return typeof value.$text === 'string' ? value.$text : undefined;",
		'  }',
		'  if (isRecord(value) && typeof value.$text === "string") return value.$text;',
		'  return undefined;',
		'}',
		'',
		'function isRecord(value: unknown): value is Record<string, unknown> {',
		"  return value !== null && typeof value === 'object' && !Array.isArray(value);",
		'}'
	];
}

export function resolveTriviaTypeNames(triviaKinds: readonly string[], nodeMap: NodeMap): string[] {
	const names = triviaKinds
		.map((kind) => nodeMap.nodes.get(kind)?.typeName)
		.filter((name): name is string => name !== undefined);
	return [...new Set(names)].sort();
}

export function buildTriviaParamType(triviaTypeNames: readonly string[], qualify = ''): string {
	const triviaType =
		triviaTypeNames.length > 0 ? triviaTypeNames.map((n) => `${qualify}${n}`).join(' | ') : 'AnyNodeData';
	const entry = `${triviaType} | string`;
	return `(${entry} | { leading?: (${entry})[]; trailing?: (${entry})[] })`;
}
