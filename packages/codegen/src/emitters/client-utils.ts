import type { StructureRow } from '@sittir/types';
import type { NodeMap } from '../compiler/types.ts';
import { innerRegions, whitespaceTrivia, type WhitespaceTrivia } from '../compiler/model/trivia.ts';
import { classifyFactoryShape, compareOrdinal, keywordPresenceValue, registeredSlots, wireRoutesOf, type WireRoutes } from './shared.ts';
import { AssembledSupertype, storageKeyOf, type AssembledNonterminal } from '../compiler/model/node-map.ts';
import { grammarTypeMapName } from './engine.ts';
import { nodeSlotNumbers } from './render-module.ts';
import { BLANK_KIND_ID } from '../compiler/model/site-preferences.ts';
import { layoutTriviaKindIds, listKindIds, namedUnitKindIds, rebuildWrapperKindIds, unitKindIds } from './wrap.ts';
import { builtFromText, storedTextKinds } from './built-from-text.ts';
import type { KindEnumEntry } from './kind-discriminant.ts';

export interface EmitClientUtilsConfig {
	grammar: string;
	nodeMap: NodeMap;
	triviaKinds?: string[];
	structure?: ReadonlyMap<number, StructureRow>;
	kindEntries?: readonly KindEnumEntry[];
}

export function emitClientUtils(config: EmitClientUtilsConfig): string {
	const map = grammarTypeMapName(config.grammar);
	return [
		'// Auto-generated by @sittir/codegen — do not edit',
		'',
		"import type { AnyUntypedNode, NodeJSONFacts, QuerySlots, StructureTable, TriviaFacts } from '@sittir/types';",
		"import { bindRuntime } from '@sittir/common/utils';",
		`import { KIND_NAMES, kindIdFromName, type ${map} } from './types.js';`,
		"import { INNER_SITES } from './consts.js';",
		"import type { TSKindId } from './kinds.js';",
		'',
		...emitTriviaFacts(
			whitespaceTrivia(config.nodeMap),
			config.triviaKinds ?? [],
			rebuildWrapperKindIds(config.nodeMap),
			listKindIds(config.nodeMap),
			layoutTriviaKindIds(config.nodeMap),
			innerRegions(config.nodeMap),
			namedUnitKindIds(config.nodeMap)
		),
		'',
		...emitQuerySlots(querySlotRows(config.nodeMap)),
		'',
		...emitJsonFacts(
			storedTextKinds(config.nodeMap, config.kindEntries).flatMap(({ node }) => (node.kindId === undefined ? [] : [node.kindId])).sort((a, b) => a - b),
			textEnvelopeContents(config.nodeMap, config.kindEntries),
			unitKindIds(config.nodeMap),
			spreadKindIds(config.nodeMap),
			registeredOptionRows(config.nodeMap)
		),
		'',
		...emitStructure(config.structure ?? new Map()),
		'',
		`export const { isNode } = bindRuntime<${map}>();`,
		''
	].join('\n');
}

function emitTriviaFacts(
	whitespace: WhitespaceTrivia | undefined,
	triviaKinds: readonly string[],
	rebuildWrappers: readonly number[],
	listKinds: readonly number[],
	layoutKinds: readonly number[],
	regions: ReadonlyMap<number, readonly string[]>,
	namedUnits: readonly number[]
): string[] {
	const facts = [
		"    kindName: (type: AnyUntypedNode['$type']) => (typeof type === 'number' ? KIND_NAMES.get(type) : type)",
		`    kinds: new Set<string>(${JSON.stringify([...triviaKinds].sort(compareOrdinal))})`,
		'    innerKinds: INNER_SITES',
		`    rebuildWrappers: new Set<number>(${JSON.stringify(rebuildWrappers)})`,
		`    listKinds: new Set<number>(${JSON.stringify(listKinds)})`,
		`    layout: new Set<number>(${JSON.stringify(layoutKinds)})`,
		`    innerRegions: new Map<number, readonly string[]>(${JSON.stringify([...regions])})`,
		`    namedUnits: new Set<number>(${JSON.stringify(namedUnits)})`,
		...(whitespace === undefined
			? []
			: [
					`    whitespace: Object.freeze({ run: /${whitespace.run.source}/${whitespace.run.flags}, kindIdByText: Object.freeze(${JSON.stringify(Object.fromEntries(whitespace.kindIdByText))}) })`
				])
	];
	return ['export const triviaFacts = Object.freeze({', facts.join(',\n'), '} satisfies TriviaFacts<TSKindId>);'];
}

type QuerySlotRow = readonly [accessor: string, slot: number, keyword: string | undefined, storageKey: string];

const RECORDER_FLAG_KEY = 'is';

export function queryRoutesOf(slot: AssembledNonterminal, nodeMap: NodeMap): WireRoutes {
	return slot.fieldName === undefined ? wireRoutesOf(slot, nodeMap) : { fields: [slot.fieldName], kinds: [] };
}

export function querySlotRows(nodeMap: NodeMap): ReadonlyMap<number, readonly QuerySlotRow[]> {
	const rows = new Map<number, readonly QuerySlotRow[]>();
	for (const node of nodeMap.nodes.values()) {
		if (node.kindId === undefined || node.slots.length === 0) continue;
		const numbers = nodeSlotNumbers(node, nodeMap);
		const row = node.slots.map((slot): QuerySlotRow => {
			if (slot.propertyName === RECORDER_FLAG_KEY)
				throw new Error(`client-utils: ${node.kind}'s slot ${slot.name} is read as \`${RECORDER_FLAG_KEY}\`, which a where condition reserves for flags`);
			const number = numbers.get(slot.storageName);
			if (number === undefined) throw new Error(`client-utils: ${node.kind}'s slot ${slot.name} has no field in its node, so a query cannot number it`);
			return [slot.propertyName, number, keywordPresenceValue(slot, nodeMap), storageKeyOf(slot.storageName)];
		});
		const claimed = rows.get(node.kindId);
		if (claimed !== undefined && JSON.stringify(claimed) !== JSON.stringify(row)) {
			throw new Error(`client-utils: kind id ${node.kindId} ('${node.kind}') has two slot tables`);
		}
		rows.set(node.kindId, row);
	}
	return new Map([...rows].sort(([a], [b]) => a - b));
}

function emitStructure(structure: ReadonlyMap<number, StructureRow>): string[] {
	const entries = [...structure].sort(([a], [b]) => a - b).map(([kindId, row]) => `    ${kindId}: ${JSON.stringify(row)}`);
	return ['export const structure: StructureTable = Object.freeze({', entries.join(',\n'), '});'];
}

function emitQuerySlots(rows: ReadonlyMap<number, readonly QuerySlotRow[]>): string[] {
	const entries = [...rows].map(([kindId, row]) => `    ${kindId}: [${row.map((entry) => `[${entry.map((part) => (part === undefined ? 'undefined' : JSON.stringify(part))).join(', ')}]`).join(', ')}]`);
	return ['export const querySlots: QuerySlots = Object.freeze({', entries.join(',\n'), '});'];
}

export function resolveTriviaTypeNames(triviaKinds: readonly string[], nodeMap: NodeMap): string[] {
	const covered = new Set(
		triviaKinds.flatMap((kind) => {
			const node = nodeMap.nodes.get(kind);
			return node instanceof AssembledSupertype ? node.subtypeNames : [];
		})
	);
	const names = triviaKinds.flatMap((kind) => {
		const node = nodeMap.nodes.get(kind);
		return node === undefined || covered.has(kind) ? [] : [node.typeName];
	});
	return [...new Set(names)].sort();
}

export function buildTriviaNodeType(triviaTypeNames: readonly string[]): string {
	return triviaTypeNames.length > 0 ? triviaTypeNames.join(' | ') : 'AnyUntypedNode';
}

function textEnvelopeContents(nodeMap: NodeMap, kindEntries: readonly KindEnumEntry[] | undefined): ReadonlyMap<number, number> {
	const rows: [number, number][] = [];
	for (const entry of builtFromText(nodeMap, kindEntries)) {
		if (entry.form !== 'alias' || entry.node.kindId === undefined) continue;
		if (entry.leaf.kindId === undefined) throw new Error(`json facts: text envelope '${entry.kind}' holds '${entry.leaf.kind}', which has no kind id`);
		rows.push([entry.node.kindId, entry.leaf.kindId]);
	}
	return new Map(rows.sort(([a], [b]) => a - b));
}

function emitJsonFacts(
	leaves: readonly number[],
	textEnvelopes: ReadonlyMap<number, number>,
	units: readonly number[],
	spread: readonly number[],
	options: ReadonlyMap<number, readonly string[]>
): string[] {
	return [
		'export const jsonFacts: NodeJSONFacts = Object.freeze({',
		'\tnames: KIND_NAMES,',
		'\tkindId: kindIdFromName,',
		'\tslots: querySlots,',
		'\tlayout: triviaFacts.layout,',
		`\tspread: new Set<number>(${JSON.stringify(spread)}),`,
		`\tleaves: new Set<number>(${JSON.stringify(leaves)}),`,
		`\ttextEnvelopes: new Map<number, number>(${JSON.stringify([...textEnvelopes])}),`,
		`\tunits: new Set<number>(${JSON.stringify(units)}),`,
		`\tblank: ${BLANK_KIND_ID},`,
		`\toptions: Object.freeze<NodeJSONFacts['options']>({${[...options].map(([kindId, names]) => ` ${kindId}: ${JSON.stringify(names)}`).join(',')}${options.size > 0 ? ' ' : ''}})`,
		'});'
	];
}

function registeredOptionRows(nodeMap: NodeMap): ReadonlyMap<number, readonly string[]> {
	const rows = new Map<number, readonly string[]>();
	for (const node of nodeMap.nodes.values()) {
		if (node.kindId === undefined || node.slots.length === 0) continue;
		const registered = registeredSlots(node).map((slot) => slot.propertyName);
		if (registered.length > 0) rows.set(node.kindId, registered);
	}
	return new Map([...rows].sort(([a], [b]) => a - b));
}

function spreadKindIds(nodeMap: NodeMap): number[] {
	return [...nodeMap.nodes.values()]
		.flatMap((node) => {
			const shape = classifyFactoryShape(node, nodeMap);
			return node.kindId !== undefined && (shape === 'elements' || shape === 'spread') ? [node.kindId] : [];
		})
		.sort((a, b) => a - b);
}
