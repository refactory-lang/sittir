export interface EmitTestsConfig {
	grammar: string;
	nodeMap: NodeMap;
	generatedIdTables?: GeneratedIdTables;
	expectTestFailures?: Readonly<Record<string, string>>;
}

function testTypeDiscriminant(
	kind: string,
	kindEntries: readonly KindEnumEntry[] | undefined,
	nodeMap: NodeMap
): string {
	if (!kindEntries) return `'${kind}'`;
	if (!hasCatalogEntry(kindEntries, kind)) return `'${kind}'`;
	return kindDiscriminantExpr(kind, nodeMap, kindEntries);
}

function dummyNodeLiteral(
	kind: string,
	dummyText: string,
	nodeMap: NodeMap | undefined,
	kindEntries: readonly KindEnumEntry[] | undefined
): string {
	const typeExpr = nodeMap ? testTypeDiscriminant(kind, kindEntries, nodeMap) : `'${kind}'`;
	return `{ $type: ${typeExpr}, $text: '${escForSource(dummyText)}', $source: 2, $named: true } as any`;
}

export function emitTests(config: EmitTestsConfig): string {
	const { nodeMap } = config;
	const allKinds = config.generatedIdTables
		? collectCatalogKinds(config.generatedIdTables)
		: Array.from(nodeMap.nodes.keys());
	const kindEntries = config.generatedIdTables
		? collectKindEntries(allKinds, nodeMap, config.generatedIdTables)
		: undefined;

	const lines: string[] = [
		'// Auto-generated by @sittir/codegen — do not edit',
		"import { describe, it, expect } from 'vitest';",
		"import { ir } from '../src/ir.js';"
	];
	if (kindEntries) {
		lines.push("import { TSKindId } from '../src/types.js';");
	}
	lines.push('');

	for (const [kind, node] of nodeMap.nodes) {
		if (kind.startsWith('_')) continue;
		if (!node.factoryName) continue;
		if (kindEntries && !hasCatalogEntry(kindEntries, kind)) continue;
		const key = node.irKey;
		if (!key) continue;
		if (!isValidIdent(key)) continue;
		if (nodeMap.polymorphFormKinds.has(kind)) continue;

		const knownFailure = config.expectTestFailures?.[kind];
		const target = knownFailure ? [] : lines;

		switch (node.modelType) {
			case 'branch':
			case 'envelope':
				emitBranchTest(target, node, kind, key, nodeMap, kindEntries);
				break;
			case 'polymorph':
				emitBranchTest(target, node, kind, key, nodeMap, kindEntries);
				break;
			case 'supertype':
				break;
			case 'list':
				emitSeparatedListTest(target, node, kind, key, kindEntries, nodeMap);
				break;
			case 'pattern':
				emitLeafTest(target, node, kind, key, kindEntries, nodeMap);
				break;
			case 'token':
				if (node instanceof AssembledKeyword) emitKeywordTest(target, node, kind, key, kindEntries, nodeMap);
				break;
			case 'enum':
				emitEnumTest(target, node, kind, key, kindEntries, nodeMap);
				break;
		}

		if (knownFailure && target.length > 0) {
			lines.push(`// known-failing: ${knownFailure}`);
			for (const line of target) {
				lines.push(line.startsWith('describe(') ? line.replace(/^describe\(/, 'describe.skip(') : line);
			}
		}
	}

	return lines.join('\n');
}

function emitBranchTest(
	lines: string[],
	node: AssembledNode,
	kind: string,
	key: string,
	nodeMap: NodeMap,
	kindEntries: readonly KindEnumEntry[] | undefined
): void {
	if (!(node instanceof AbstractAssembledCompound) || node instanceof AssembledList || node.hoisted) return;
	if (classifyChildFactorySurface(node, nodeMap) !== null) {
		emitContainerTest(lines, node, kind, key, kindEntries, nodeMap);
		return;
	}

	const { typeConfigArg, renderConfigArg } = factoryCallArgs(node, nodeMap, kindEntries);
	lines.push(`describe('${kind}', () => {`);
	lines.push(`  it('factory produces correct type', () => {`);
	lines.push(`    const node = ir.${key}(${typeConfigArg});`);
	lines.push(`    expect(node.$type).toBe(${testTypeDiscriminant(kind, kindEntries, nodeMap)});`);
	lines.push(`    expect(node.$source).toBe(2);`);
	lines.push('  });');

	const hasRenderContent = renderConfigArg !== '{}';
	if (hasRenderContent) {
		lines.push(`  it('render produces non-empty string', () => {`);
		lines.push(`    const node = ir.${key}(${renderConfigArg});`);
		lines.push(`    expect(node.$render!().length).toBeGreaterThan(0);`);
		lines.push('  });');
	} else {
		lines.push(`  it('render does not throw on minimal config', () => {`);
		lines.push(`    const node = ir.${key}(${renderConfigArg});`);
		lines.push(`    expect(() => node.$render!()).not.toThrow();`);
		lines.push('  });');
	}

	lines.push('});');
	lines.push('');
}

function factoryCallArgs(
	node: AssembledBranch | AssembledEnvelope | AssembledPolymorph,
	nodeMap: NodeMap,
	kindEntries: readonly KindEnumEntry[] | undefined,
	strict = false
): { typeConfigArg: string; renderConfigArg: string } {
	const typeConfigParts: string[] = [];
	for (const f of node.fields) {
		if (isRequired(f)) {
			typeConfigParts.push(`${f.configKey}: ${dummyValue(f, nodeMap, kindEntries, strict)}`);
		}
	}
	const renderConfigParts = [...typeConfigParts];

	const singleFieldSlot = resolveDirectFactorySlot(node, nodeMap);
	const singleFieldIsKindEnum =
		!strict && singleFieldSlot !== undefined && kindEnumTextIdPairs(singleFieldSlot, nodeMap, kindEntries).length > 0;

	let typeConfigArg: string;
	let renderConfigArg: string;
	if (singleFieldSlot && !singleFieldIsKindEnum) {
		const sole = singleFieldSlot;
		const dummy = dummyValue(sole, nodeMap, kindEntries, strict);
		typeConfigArg = isRequired(sole) ? dummy : '';
		renderConfigArg = dummy;
	} else {
		typeConfigArg = typeConfigParts.length > 0 ? `{ ${typeConfigParts.join(', ')} }` : '{}';
		renderConfigArg = renderConfigParts.length > 0 ? `{ ${renderConfigParts.join(', ')} }` : '{}';
	}
	return { typeConfigArg, renderConfigArg };
}

function containerCallArgs(
	node: AssembledBranch | AssembledEnvelope | AssembledPolymorph,
	nodeMap: NodeMap,
	kindEntries: readonly KindEnumEntry[] | undefined
): string {
	const facts = soleSlotFacts(node, nodeMap);
	const requiredSingular = facts && !facts.multiple && facts.required;
	const anyNonEmpty = facts?.nonEmpty ?? false;
	const candidateKindNames = facts
		? facts.slot.values
				.map((v) => v.parseKind?.name ?? (isNodeRef(v) ? storageKindOfRef(v.node) : undefined))
				.filter((n) => n !== undefined)
		: [];
	const firstKindName =
		candidateKindNames.length > 0 ? resolveConcreteKind(candidateKindNames, nodeMap, kindEntries) : undefined;
	const placeholder =
		(requiredSingular || anyNonEmpty) && firstKindName
			? buildDummyStub(firstKindName, nodeMap, kindEntries, 0, new Set())
			: '';

	return placeholder;
}

function emitContainerTest(
	lines: string[],
	node: AssembledNode,
	kind: string,
	key: string,
	kindEntries: readonly KindEnumEntry[] | undefined,
	nodeMap: NodeMap
): void {
	if (!(node instanceof AbstractAssembledCompound) || node instanceof AssembledList) return;
	if (classifyChildFactorySurface(node, nodeMap) === null) return;

	const placeholder = containerCallArgs(node, nodeMap, kindEntries);
	lines.push(`describe('${kind}', () => {`);
	lines.push(`  it('factory produces correct type', () => {`);
	lines.push(`    const node = ir.${key}(${placeholder});`);
	lines.push(`    expect(node.$type).toBe(${testTypeDiscriminant(kind, kindEntries, nodeMap)});`);
	lines.push(`    expect(node.$source).toBe(2);`);
	lines.push('  });');
	lines.push('});');
	lines.push('');
}

function emitSeparatedListTest(
	lines: string[],
	node: AssembledNode,
	kind: string,
	key: string,
	kindEntries: readonly KindEnumEntry[] | undefined,
	nodeMap: NodeMap
): void {
	if (node.modelType !== 'list') return;

	const contentSlot = buildSeparatedListContentSlot(node);
	const elementsArg = `[${dummyValueForField(contentSlot, nodeMap, kindEntries, 0, new Set())}]`;
	const callArgs = `...${elementsArg}`;

	lines.push(`describe('${kind}', () => {`);
	lines.push(`  it('factory produces correct type', () => {`);
	lines.push(`    const node = ir.${key}(${callArgs});`);
	lines.push(`    expect(node.$type).toBe(${testTypeDiscriminant(kind, kindEntries, nodeMap)});`);
	lines.push(`    expect(node.$source).toBe(2);`);
	lines.push('  });');
	lines.push(`  it('render produces non-empty string', () => {`);
	lines.push(`    const node = ir.${key}(${callArgs});`);
	lines.push(`    expect(node.$render!().length).toBeGreaterThan(0);`);
	lines.push('  });');
	lines.push('});');
	lines.push('');
}

function emitLeafTest(
	lines: string[],
	node: AssembledNode,
	kind: string,
	key: string,
	kindEntries: readonly KindEnumEntry[] | undefined,
	nodeMap: NodeMap
): void {
	const pattern = node.modelType === 'pattern' ? node.pattern : undefined;
	const sample = pickSampleForPattern(pattern);
	if (sample === null) {
		return;
	}
	lines.push(`describe('${kind}', () => {`);
	lines.push(`  it('factory produces correct type', () => {`);
	lines.push(`    const node = ir.${key}(${JSON.stringify(sample)});`);
	lines.push(`    expect(node.$type).toBe(${testTypeDiscriminant(kind, kindEntries, nodeMap)});`);
	lines.push(`    expect(node.$source).toBe(2);`);
	lines.push(`    expect(node.$text).toBe(${JSON.stringify(sample)});`);
	lines.push('  });');
	lines.push('});');
	lines.push('');
}

function pickSampleForPattern(pattern: string | undefined): string | null {
	if (!pattern) return 'test';
	const candidates = [
		'test',
		'a',
		'x',
		'1',
		'0',
		'_a',
		'$x',
		'#!/bin/sh',
		'/* */',
		'"hello"',
		"'h'",
		'0x1',
		'1.0',
		'1e0',
		'1u32',
		'\n',
		' '
	];
	let re: RegExp | null = null;
	try {
		re = new RegExp(`^(?:${pattern})$`, 'u');
	} catch {
		try {
			re = new RegExp(`^(?:${pattern})$`);
		} catch {
			return null;
		}
	}
	for (const c of candidates) {
		if (re.test(c)) return c;
	}
	return null;
}

function emitKeywordTest(
	lines: string[],
	node: AssembledNode,
	kind: string,
	key: string,
	kindEntries: readonly KindEnumEntry[] | undefined,
	nodeMap: NodeMap
): void {
	if (!(node instanceof AssembledKeyword)) return;
	lines.push(`describe(${JSON.stringify(kind)}, () => {`);
	lines.push(`  it('factory produces keyword', () => {`);
	lines.push(`    const node = ir.${key}();`);
	lines.push(`    expect(node.$type).toBe(${testTypeDiscriminant(kind, kindEntries, nodeMap)});`);
	lines.push(`    expect(node.$source).toBe(2);`);
	lines.push(`    expect(node.$text).toBe(${JSON.stringify(node.text)});`);
	lines.push('  });');
	lines.push('});');
	lines.push('');
}

function emitEnumTest(
	lines: string[],
	node: AssembledNode,
	kind: string,
	key: string,
	kindEntries: readonly KindEnumEntry[] | undefined,
	nodeMap: NodeMap
): void {
	if (node.modelType !== 'enum') return;
	const first = node.values[0];
	if (!first) return;
	lines.push(`describe('${kind}', () => {`);
	lines.push(`  it('factory accepts valid value', () => {`);
	lines.push(`    const node = ir.${key}('${escForSource(first)}');`);
	lines.push(`    expect(node.$type).toBe(${testTypeDiscriminant(kind, kindEntries, nodeMap)});`);
	lines.push(`    expect(node.$source).toBe(2);`);
	lines.push('  });');
	lines.push('});');
	lines.push('');
}

function resolveConcreteKind(
	candidates: readonly string[],
	nodeMap: NodeMap,
	kindEntries: readonly KindEnumEntry[] | undefined
): string {
	const seen = new Set<string>();
	const nonLeafCandidates: string[] = [];
	const queue = [...candidates];
	while (queue.length > 0) {
		const current = queue.shift()!;
		if (seen.has(current)) continue;
		seen.add(current);
		const node = nodeMap.nodes.get(current);
		if (!node) continue;
		if (node instanceof AssembledSupertype) {
			queue.push(...node.subtypeNames);
			continue;
		}
		if (kindEntries && !hasCatalogEntry(kindEntries, current)) continue;
		if (node.modelType === 'pattern' || node.modelType === 'token' || node.modelType === 'enum') {
			return current;
		}
		nonLeafCandidates.push(current);
	}
	return nonLeafCandidates[0] ?? candidates[0] ?? '';
}

const MAX_DUMMY_DEPTH = 6;

function dummyValueForField(
	field: AssembledNonterminal,
	nodeMap: NodeMap,
	kindEntries: readonly KindEnumEntry[] | undefined,
	depth: number,
	visiting: ReadonlySet<string>
): string {
	const storageInfo = resolveFieldStorageInfo(field, nodeMap, kindEntries);
	if (depth === 0) {
		if (storageInfo.kind === 'boolean') return 'true';
		if (storageInfo.kind === 'bitflag') return '0 as never';
		if (storageInfo.kind === 'kindEnum') {
			const text = storageInfo.texts[0];
			return text !== undefined ? JSON.stringify(text) : "'test' as any";
		}
	} else {
		if (storageInfo.kind === 'boolean') return 'true as never';
		if (storageInfo.kind === 'bitflag') return '0 as never';
		if (storageInfo.kind === 'kindEnum') {
			const enumKind = storageInfo.enumKinds[0];
			if (enumKind !== undefined && kindEntries && hasCatalogEntry(kindEntries, enumKind)) {
				return `${kindDiscriminantExpr(enumKind, nodeMap, kindEntries)} as never`;
			}
			const text = storageInfo.texts[0];
			return text !== undefined ? JSON.stringify(text) : "'test' as any";
		}
	}

	const kinds = slotKindNames(field);
	if (kinds.length === 0) return "'test' as any";
	const concrete = resolveConcreteKind(kinds, nodeMap, kindEntries);
	return buildDummyStub(concrete, nodeMap, kindEntries, depth, visiting);
}

function buildDummyStub(
	kind: string,
	nodeMap: NodeMap,
	kindEntries: readonly KindEnumEntry[] | undefined,
	depth: number,
	visiting: ReadonlySet<string>
): string {
	const node = nodeMap.nodes.get(kind) ?? nodeMap.nodes.get(`_${kind}`);
	const dummyText = node ? dummyTextForKind(kind, nodeMap) : 'test';
	const base = dummyNodeLiteral(kind, dummyText, nodeMap, kindEntries);
	if (!node || (!(node instanceof AbstractAssembledCompound) && !(node instanceof AssembledList))) return base;
	if (depth >= MAX_DUMMY_DEPTH || visiting.has(kind)) return base;

	const nextVisiting = new Set(visiting);
	nextVisiting.add(kind);
	const fieldParts: string[] = [];
	for (const f of allSlotsOf(node)) {
		if (!isRequired(f)) continue;
		const value = isMultiple(f)
			? `[${dummyValueForField(f, nodeMap, kindEntries, depth + 1, nextVisiting)}]`
			: dummyValueForField(f, nodeMap, kindEntries, depth + 1, nextVisiting);
		fieldParts.push(`${f.storageKey}: ${value}`);
	}
	if (fieldParts.length === 0) return base;
	return base.replace(/\}\s*as any$/, `, ${fieldParts.join(', ')} } as any`);
}

function dummyValue(
	field: AssembledNonterminal,
	nodeMap?: NodeMap,
	kindEntries?: readonly KindEnumEntry[],
	strict = false
): string {
	if (nodeMap) {
		const kw = keywordPresenceKind(field, nodeMap);
		if (kw === 'boolean') return 'true';
		if (kw === 'bitflag') return '0 as never';
		if (strict) {
			const storageInfo = resolveFieldStorageInfo(field, nodeMap, kindEntries);
			const text = storageInfo.texts[0];
			if (storageInfo.kind === 'kindEnum' && text !== undefined) return kindEnumConfigValue(text, kindEntries);
		}
	}
	if (!nodeMap) {
		const kinds = slotKindNames(field);
		if (isMultiple(field)) {
			return kinds.length > 0 ? `[${dummyNodeLiteral(kinds[0]!, 'test', undefined, kindEntries)}]` : `['test' as any]`;
		}
		return kinds.length > 0 ? dummyNodeLiteral(kinds[0]!, 'test', undefined, kindEntries) : "'test' as any";
	}
	if (isMultiple(field)) {
		return `[${dummyValueForField(field, nodeMap, kindEntries, 0, new Set())}]`;
	}
	return dummyValueForField(field, nodeMap, kindEntries, 0, new Set());
}

function dummyTextForKind(kind: string, nodeMap: NodeMap): string {
	const node = nodeMap.nodes.get(kind);
	if (!node) return 'test';
	if (node.modelType === 'token') return node.text;
	if (node.modelType === 'enum' && node.values.length > 0) return node.values[0]!;
	return 'test';
}
