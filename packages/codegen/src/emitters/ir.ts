import type { NodeMap } from '../compiler/types.ts';
import { isVisibleTextLeaf, isHiddenPunctuationLeaf } from '../compiler/model/node-map.ts';
import type { GeneratedIdTables } from '../compiler/generated-metadata.ts';
import type { AssembledNode } from '../compiler/model/node-map.ts';
import {
	AbstractAssembledCompound,
	AssembledList,
	AssembledSupertype,
	AssembledPattern
} from '../compiler/model/node-map.ts';
import { isValidIdent, irNamespacesChildFactory, compareOrdinal, lexedContentSlot } from './shared.ts';
import { isHiddenKind } from '../dsl/rule-patterns.ts';
import { supertypeMemberName } from '../compiler/variant-structural.ts';
import { collectKindEntries, collectCatalogKinds, hasCatalogEntry,
} from './kind-discriminant.ts';
import { bundleEntries, flattenedVariantParents } from './overlays/module.ts';
import type { GrammarRoles, Role } from '../scm/extract-roles.ts';

export interface EmitIrConfig {
	grammar: string;
	nodeMap: NodeMap;
	generatedIdTables?: GeneratedIdTables;
	grammarRoles?: GrammarRoles;
}

export function emitIr(config: EmitIrConfig): string {
	const { nodeMap, generatedIdTables, grammarRoles } = config;

	const kindEntries = generatedIdTables
		? collectKindEntries(collectCatalogKinds(generatedIdTables), nodeMap, generatedIdTables)
		: undefined;

	const bundleKeyByKind = new Map(bundleEntries(nodeMap, generatedIdTables).map((e) => [e.node.kind, e.exportName]));
	const bundleRef = (node: AssembledNode): string => {
		const key = bundleKeyByKind.get(node.kind);
		if (key === undefined) {
			throw new Error(`[ir] no bundle entry for kind '${node.kind}' — flat/group emission and bundleEntries disagree`);
		}
		return `F.${key}`;
	};

	const lines: string[] = [
		'// Auto-generated by @sittir/codegen — do not edit',
		'//',
		'// `ir.*` — flat namespace: every grammar kind exposed as `ir.<camelCaseKind>`.',
		'// `ir.<supertype>.*` — grouped namespaces: each member re-keyed by its',
		'//   supertype-stripped short name (e.g. `ir.expression.binary` === `ir.binaryExpression`).',
		'//',
		'// Both surfaces resolve to the same callable bundle: calling an entry',
		'// coerces its input; `.strict` is the strict factory.',
		'//',
		'// Edge case: `readNode()` output has no `$source` provenance. To pass it',
		'// straight to an entry, use the typed wrapper (`readTreeNode`) so the',
		'// entry sees a wrapped node and takes the identity quick-return path.',
		'',
		"import * as F from './factories/index.js';",
		''
	];

	const body: string[] = [];
	const groupBlocks: string[] = [];
	const groupNames: string[] = [];
	const usedGroupNames = new Set<string>();

	let hasSynonyms = false;
	if (grammarRoles) {
		const synonymLines = emitSynonymNamespace(grammarRoles, nodeMap);
		if (synonymLines.length > 0) {
			hasSynonyms = true;
			body.push(...synonymLines);
			body.push('');
		}
	}

	const flatRefByKey = new Map<string, string>();
	for (const { key, node } of bundleEntries(nodeMap, generatedIdTables)) flatRefByKey.set(key, bundleRef(node));
	for (const [kind, node] of nodeMap.nodes) {
		if (isFlatLeafOrKeyword(kind, node, kindEntries)) flatRefByKey.set(node.irKey!, `F.${node.rawFactoryName}`);
	}
	let needsAttachProps = false;
	const flattenedParents = flattenedVariantParents(nodeMap, generatedIdTables);
	const flattenedKinds = new Set(flattenedParents.map((parent) => parent.node.kind));
	const flattenedKeyByKind = new Map(flattenedParents.map((parent) => [parent.node.kind, parent.key] as const));

	for (const [kind, node] of nodeMap.nodes) {
		if (!(node instanceof AssembledSupertype) || flattenedKinds.has(kind)) continue;
		const sup = node;
		const groupName = groupNameFor(kind);
		if (!isValidIdent(groupName) || usedGroupNames.has(groupName)) continue;

		const memberEntries: string[] = [];
		const memberTypeEntries: string[] = [];
		const usedMemberKeys = new Set<string>();
		for (const subKind of sup.subtypeNames) {
			if (subKind.startsWith('_')) continue;
			const sub = nodeMap.nodes.get(subKind);
			if (!sub) continue;
			const flattenedKey = flattenedKeyByKind.get(subKind);
			if (flattenedKey !== undefined) {
				const memberKey = memberKeyFor(subKind, kind);
				if (!isValidIdent(memberKey) || usedMemberKeys.has(memberKey)) continue;
				usedMemberKeys.add(memberKey);
				memberEntries.push(`  ${memberKey}: F.${flattenedKey},`);
				memberTypeEntries.push(`  readonly ${memberKey}: typeof F.${flattenedKey};`);
				continue;
			}
			if (sub.factoryInline) continue;
			if (!sub.rawFactoryName) continue;
			if (sub instanceof AssembledSupertype || isHiddenPunctuationLeaf(sub)) continue;
			if ((sub instanceof AbstractAssembledCompound || sub instanceof AssembledList) && !bundleKeyByKind.has(subKind)) continue;
			if (kindEntries && !hasCatalogEntry(kindEntries, subKind)) continue;
			const memberKey = memberKeyFor(subKind, kind);
			if (!isValidIdent(memberKey) || usedMemberKeys.has(memberKey)) continue;
			usedMemberKeys.add(memberKey);

			if (sub instanceof AbstractAssembledCompound || sub instanceof AssembledList) {
				if (!sub.fromFunctionName) continue;
				const ref = bundleRef(sub);
				memberEntries.push(`  ${memberKey}: ${ref},`);
				memberTypeEntries.push(`  readonly ${memberKey}: typeof ${ref};`);
			} else if (isVisibleTextLeaf(sub) || sub instanceof AssembledPattern) {
				if (!sub.rawFactoryName) continue;
				memberEntries.push(`  ${memberKey}: F.${sub.rawFactoryName},`);
				memberTypeEntries.push(`  readonly ${memberKey}: typeof F.${sub.rawFactoryName};`);
			}
		}
		if (memberEntries.length === 0) continue;
		usedGroupNames.add(groupName);
		groupNames.push(groupName);

		const sameNamedKind = flatRefByKey.get(groupName);
		if (sameNamedKind === undefined) {
			groupBlocks.push(`export const ${groupName}: {`);
			groupBlocks.push(...memberTypeEntries);
			groupBlocks.push('} = {');
			groupBlocks.push(...memberEntries);
			groupBlocks.push('};');
		} else {
			needsAttachProps = true;
			groupBlocks.push(`export const ${groupName}: typeof ${sameNamedKind} & {`);
			groupBlocks.push(...memberTypeEntries);
			groupBlocks.push(`} = attachProps(${sameNamedKind}, {`);
			groupBlocks.push(...memberEntries);
			groupBlocks.push('});');
		}
		groupBlocks.push('');
	}

	const variantParentKeys: string[] = [];
	for (const { key, variants } of flattenedParents) {
		if (usedGroupNames.has(key)) continue;
		if (variants.every((route) => route.minted === true)) {
			variantParentKeys.push(key);
			continue;
		}
		usedGroupNames.add(key);
		groupNames.push(key);
		const sameNamedKind = flatRefByKey.get(key);
		if (sameNamedKind === undefined) {
			groupBlocks.push(`export const ${key}: typeof F.${key} = F.${key};`, '');
			continue;
		}
		needsAttachProps = true;
		groupBlocks.push(`export const ${key}: typeof ${sameNamedKind} & typeof F.${key} = attachProps(${sameNamedKind}, F.${key});`, '');
	}
	if (groupBlocks.length > 0) {
		body.push('// Supertype-grouped sub-namespaces — tree-shakeable top-level consts.');
		body.push('// Also attached to `ir.*` below for nested access (e.g. `ir.expression.binary`).');
		body.push(...groupBlocks);
	}

	const flatKeys = new Set<string>();
	for (const [kind, node] of nodeMap.nodes) {
		if (kind.startsWith('_') || node.factoryInline) continue;
		if (!node.irKey || !node.rawFactoryName) continue;
		if (!isValidIdent(node.irKey)) continue;
		const isStructuralFactory =
			(node instanceof AbstractAssembledCompound && node.annotations?.hoisted !== true) || node instanceof AssembledList;
		const isLeafFactoryNode = isVisibleTextLeaf(node) || node instanceof AssembledPattern;
		if (!isStructuralFactory && !isLeafFactoryNode) {
			continue;
		}
		if (isStructuralFactory && !node.fromFunctionName) continue;
		if (kindEntries && !hasCatalogEntry(kindEntries, kind)) continue;
		flatKeys.add(node.irKey);
	}
	const shortAliasBundles = new Map<string, string>();
	for (const [kind, node] of nodeMap.nodes) {
		if (!(node instanceof AssembledSupertype)) continue;
		const sup = node;
		for (const subKind of sup.subtypeNames) {
			if (subKind.startsWith('_')) continue;
			const sub = nodeMap.nodes.get(subKind);
			if (!sub?.rawFactoryName || sub.factoryInline || sub.annotations?.tokenForm === true) continue;
			if (kindEntries && !hasCatalogEntry(kindEntries, subKind)) continue;
			const alias = memberKeyFor(subKind, kind);
			if (!isValidIdent(alias) || flatKeys.has(alias) || usedGroupNames.has(alias)) continue;
			let bundle: string | undefined;
			if ((sub instanceof AbstractAssembledCompound && sub.annotations?.hoisted !== true) || sub instanceof AssembledList) {
				if (!sub.fromFunctionName) continue;
				bundle = bundleRef(sub);
			} else if (isVisibleTextLeaf(sub) || sub instanceof AssembledPattern) {
				if (!sub.rawFactoryName) continue;
				bundle = `F.${sub.rawFactoryName}`;
			} else {
				continue;
			}
			if (shortAliasBundles.has(alias)) continue;
			shortAliasBundles.set(alias, bundle);
		}
	}

	const irTypeMembers: string[] = [];
	const irValueLines: string[] = [];
	irValueLines.push('  // Node factories');
	for (const { key, node } of bundleEntries(nodeMap, generatedIdTables)) {
		if (usedGroupNames.has(key)) continue;
		const ref = bundleRef(node);
		irValueLines.push(`  ${key}: ${ref},`);
		irTypeMembers.push(`  readonly ${key}: typeof ${ref};`);
	}
	for (const key of variantParentKeys) {
		irValueLines.push(`  ${key}: F.${key},`);
		irTypeMembers.push(`  readonly ${key}: typeof F.${key};`);
	}

	irValueLines.push('');

	irValueLines.push('  // Keyword factories');
	for (const [kind, node] of nodeMap.nodes) {
		if (!isVisibleTextLeaf(node) || !isFlatLeafOrKeyword(kind, node, kindEntries) || node.annotations?.tokenForm === true) continue;
		if (usedGroupNames.has(node.irKey!)) continue;
		irValueLines.push(`  ${node.irKey}: F.${node.rawFactoryName},`);
		irTypeMembers.push(`  readonly ${node.irKey}: typeof F.${node.rawFactoryName};`);
	}
	irValueLines.push('');

	irValueLines.push('  // Leaf node factories');
	for (const [kind, node] of nodeMap.nodes) {
		if (!(node instanceof AssembledPattern) || node.annotations?.tokenForm === true) continue;
		if (!isFlatLeafOrKeyword(kind, node, kindEntries)) continue;
		if (usedGroupNames.has(node.irKey!)) continue;
		irValueLines.push(`  ${node.irKey}: F.${node.rawFactoryName},`);
		irTypeMembers.push(`  readonly ${node.irKey}: typeof F.${node.rawFactoryName};`);
	}
	if (shortAliasBundles.size > 0) {
		irValueLines.push('');
		irValueLines.push('  // Supertype-stripped short aliases');
		for (const [alias, bundle] of [...shortAliasBundles.entries()].sort(([a], [b]) => compareOrdinal(a, b))) {
			irValueLines.push(`  ${alias}: ${bundle},`);
			irTypeMembers.push(`  readonly ${alias}: typeof ${bundle};`);
		}
	}
	if (groupNames.length > 0 || hasSynonyms) {
		irValueLines.push('');
		irValueLines.push('  // Supertype-grouped sub-namespaces (also exported standalone above)');
		for (const g of groupNames) {
			irValueLines.push(`  ${g},`);
			irTypeMembers.push(`  readonly ${g}: typeof ${g};`);
		}
		if (hasSynonyms) {
			irValueLines.push('  synonym,');
			irTypeMembers.push('  readonly synonym: typeof synonym;');
		}
	}
	if (needsAttachProps) lines.splice(lines.indexOf("import * as F from './factories/index.js';") + 1, 0, "import { attachProps } from './utils.js';");
	body.push('export const ir: {');
	body.push(...irTypeMembers);
	body.push('} = {');
	body.push(...irValueLines);
	body.push('};');

	return [...lines, ...body].join('\n');
}

function isFlatLeafOrKeyword(
	kind: string,
	node: AssembledNode,
	kindEntries: ReturnType<typeof collectKindEntries> | undefined
): boolean {
	if (!node.userFacing || node.factoryInline) return false;
	if (isVisibleTextLeaf(node) ? isHiddenKind(kind) : !(node instanceof AssembledPattern)) return false;
	if (!node.irKey || !node.rawFactoryName || !isValidIdent(node.irKey) || node.irKey.startsWith('_')) return false;
	return !kindEntries || hasCatalogEntry(kindEntries, kind);
}

function groupNameFor(supertypeKind: string): string {
	const bare = supertypeKind.replace(/^_+/, '');
	return toCamel(bare);
}

function memberKeyFor(memberKind: string, supertypeKind: string): string {
	return toCamel(supertypeMemberName(memberKind, supertypeKind));
}

function toCamel(snake: string): string {
	const parts = snake.split('_').filter((p) => p.length > 0);
	if (parts.length === 0) return snake;
	return (
		parts[0] +
		parts
			.slice(1)
			.map((p) => p.charAt(0).toUpperCase() + p.slice(1))
			.join('')
	);
}

function isPolymorphTextParent(node: AssembledNode): boolean {
	return node instanceof AssembledSupertype && node.irKey !== undefined && node.annotations?.hoisted !== true;
}

function isTextRoleTarget(node: AssembledNode): boolean {
	return isLeafFactory(node) || isPolymorphTextParent(node);
}

function roleFactoryRef(node: AssembledNode): string {
	return isPolymorphTextParent(node) ? `F.${node.irKey}` : factoryRef(node);
}

function roleReturnType(node: AssembledNode): string {
	return `ReturnType<typeof ${roleFactoryRef(node)}>`;
}

function resolveRoleNodes(role: Role, grammarRoles: GrammarRoles, nodeMap: NodeMap, includePolymorphParents = false): AssembledNode[] {
	const kindNames = grammarRoles.get(role);
	const nodes: AssembledNode[] = [];
	const seen = new Set<string>();
	for (const kind of kindNames) {
		const node = nodeMap.nodes.get(kind) ?? nodeMap.nodes.get(`_${kind}`);
		if (node && (node.rawFactoryName || (includePolymorphParents && isPolymorphTextParent(node))) && !seen.has(node.kind)) {
			seen.add(node.kind);
			nodes.push(node);
		}
	}
	return nodes;
}

function isLeafFactory(node: AssembledNode): boolean {
	return (
		(node instanceof AssembledPattern || isVisibleTextLeaf(node) || lexedContentSlot(node) !== undefined) &&
		node.rawFactoryName !== undefined
	);
}

function factoryRef(node: AssembledNode): string {
	return lexedContentSlot(node) === undefined ? `F.${node.rawFactoryName}` : `F.${node.factoryName}`;
}

function returnTypeExpr(node: AssembledNode): string {
	return `ReturnType<typeof ${factoryRef(node)}>`;
}

function emitSynonymNamespace(grammarRoles: GrammarRoles, nodeMap: NodeMap): string[] {
	const fns: string[] = [];

	emitSynonymBoolean(grammarRoles, nodeMap, fns);
	emitSynonymNumber(grammarRoles, nodeMap, fns);
	emitSynonymString(grammarRoles, nodeMap, fns);
	emitSynonymComment(grammarRoles, nodeMap, fns);
	emitSynonymType(grammarRoles, nodeMap, fns);
	emitSynonymIdentifier(grammarRoles, nodeMap, fns);
	emitSynonymAliases(grammarRoles, nodeMap, fns);

	if (fns.length === 0) return [];

	const lines: string[] = [];
	lines.push("// Role synonyms — resolve a native JS value to this grammar's node for that role.");
	lines.push('// Tree-shakeable via the standalone `synonym` export; also reachable as `ir.synonym.*`.');
	lines.push('export const synonym = {');
	lines.push(...fns);
	lines.push('} as const;');
	return lines;
}

function emitSynonymBoolean(grammarRoles: GrammarRoles, nodeMap: NodeMap, fns: string[]): void {
	const nodes = resolveRoleNodes('boolean', grammarRoles, nodeMap);
	if (nodes.length === 0) return;

	const leafNode = nodes.find((n) => isLeafFactory(n) && !isVisibleTextLeaf(n));
	if (leafNode) {
		fns.push(`  boolean(value: boolean): ${returnTypeExpr(leafNode)} {`);
		fns.push(`    return ${factoryRef(leafNode)}(value ? 'true' : 'false');`);
		fns.push('  },');
		return;
	}

	const trueNode = nodes.find((n) => n.kind === 'true');
	const falseNode = nodes.find((n) => n.kind === 'false');
	if (trueNode && falseNode) {
		const retType = `${returnTypeExpr(trueNode)} | ${returnTypeExpr(falseNode)}`;
		fns.push(`  boolean(value: boolean): ${retType} {`);
		fns.push(`    return value ? ${factoryRef(trueNode)}() : ${factoryRef(falseNode)}();`);
		fns.push('  },');
		return;
	}

	const first = nodes[0];
	if (first && isLeafFactory(first)) {
		fns.push(`  boolean(value: boolean): ${returnTypeExpr(first)} {`);
		fns.push(`    return ${factoryRef(first)}(value ? 'true' : 'false');`);
		fns.push('  },');
	}
}

function emitSynonymNumber(grammarRoles: GrammarRoles, nodeMap: NodeMap, fns: string[]): void {
	const nodes = resolveRoleNodes('number', grammarRoles, nodeMap, true);
	const leafNodes = nodes.filter(isTextRoleTarget);
	if (leafNodes.length === 0) return;

	const floatNodes = resolveRoleNodes('number.float', grammarRoles, nodeMap, true).filter(isTextRoleTarget);
	const floatSet = new Set(floatNodes.map((n) => n.kind));
	const intNodes = leafNodes.filter((n) => !floatSet.has(n.kind));

	const intNode = intNodes[0];
	const floatNode = floatNodes[0];

	if (intNode && floatNode) {
		const retType = `${roleReturnType(intNode)} | ${roleReturnType(floatNode)}`;
		fns.push(`  number: Object.assign(`);
		fns.push(`    function number(value: number): ${retType} {`);
		fns.push(`      return Number.isInteger(value)`);
		fns.push(`        ? ${roleFactoryRef(intNode)}(String(value))`);
		fns.push(`        : ${roleFactoryRef(floatNode)}(String(value));`);
		fns.push(`    },`);
		fns.push(`    {`);
		fns.push(
			`      integer(value: number): ${roleReturnType(intNode)} { return ${roleFactoryRef(intNode)}(String(value)); },`
		);
		fns.push(
			`      float(value: number): ${roleReturnType(floatNode)} { return ${roleFactoryRef(floatNode)}(String(value)); },`
		);
		fns.push(`    }`);
		fns.push(`  ),`);
	} else {
		const node = intNode ?? floatNode ?? leafNodes[0];
		if (!node) return;
		fns.push(`  number(value: number): ${roleReturnType(node)} {`);
		fns.push(`    return ${roleFactoryRef(node)}(String(value));`);
		fns.push('  },');
	}
}

function emitSynonymString(grammarRoles: GrammarRoles, nodeMap: NodeMap, fns: string[]): void {
	const nodes = resolveRoleNodes('string', grammarRoles, nodeMap);
	if (nodes.length === 0) return;

	const primaryNode = nodes.find((n) => /string/.test(n.kind) && !/char|raw|template|regex/.test(n.kind));
	if (!primaryNode) return;

	if (isLeafFactory(primaryNode)) {
		fns.push(`  string(value: string): ${returnTypeExpr(primaryNode)} {`);
		fns.push(`    return ${factoryRef(primaryNode)}(value);`);
		fns.push('  },');
		return;
	}

	const contentNode = nodeMap.nodes.get('string_content');
	if (contentNode && isLeafFactory(contentNode) && irNamespacesChildFactory(primaryNode, nodeMap)) {
		fns.push(`  string(value: string): ${returnTypeExpr(primaryNode)} {`);
		fns.push(`    return ${factoryRef(primaryNode)}(${factoryRef(contentNode)}(value));`);
		fns.push('  },');
	}
}

function emitSynonymComment(grammarRoles: GrammarRoles, nodeMap: NodeMap, fns: string[]): void {
	const refs = new Map<string, string>();
	const ref = (node: AssembledNode): string => refs.get(node.kind) ?? factoryRef(node);
	const returnType = (node: AssembledNode): string => `ReturnType<typeof ${ref(node)}>`;
	const nodes = grammarRoles
		.get('trivia')
		.flatMap((kind) => {
			const node = nodeMap.nodes.get(kind) ?? nodeMap.nodes.get(`_${kind}`);
			if (node instanceof AssembledSupertype) {
				return [...node.subtypeNames].flatMap((name) => {
					const sub = nodeMap.nodes.get(name);
					if (sub === undefined) return [];
					const variant = name.startsWith(`${node.kind}_`) ? name.slice(node.kind.length + 1) : undefined;
					if (variant !== undefined) refs.set(name, `F.${node.irKey}.${variant}`);
					return [sub];
				});
			}
			return node === undefined ? [] : [node];
		})
		.filter((node, i, all) => node.rawFactoryName !== undefined && all.findIndex((other) => other.kind === node.kind) === i);
	if (nodes.length === 0) return;

	const leafNodes = nodes.filter(isLeafFactory);

	if (leafNodes.length === 1) {
		const node = leafNodes[0]!;
		fns.push(`  comment(text: string): ${returnType(node)} {`);
		fns.push(`    return ${ref(node)}(text);`);
		fns.push('  },');
		return;
	}

	if (leafNodes.length > 1) {
		const lineNode = leafNodes.find((n) => /line/.test(n.kind));
		const blockNode = leafNodes.find((n) => /block/.test(n.kind));
		if (lineNode && blockNode) {
			fns.push(`  comment: Object.assign(`);
			fns.push(`    function comment(content: string): ${returnType(lineNode)} {`);
			fns.push(`      return ${ref(lineNode)}(content);`);
			fns.push(`    },`);
			fns.push(`    {`);
			fns.push(`      line(text: string): ${returnType(lineNode)} { return ${ref(lineNode)}(text); },`);
			fns.push(
				`      block(text: string): ${returnType(blockNode)} { return ${ref(blockNode)}(text); },`
			);
			fns.push(`    }`);
			fns.push(`  ),`);
			return;
		}
		const first = leafNodes[0]!;
		fns.push(`  comment(text: string): ${returnType(first)} {`);
		fns.push(`    return ${ref(first)}(text);`);
		fns.push('  },');
		return;
	}
}

function emitSynonymType(grammarRoles: GrammarRoles, nodeMap: NodeMap, fns: string[]): void {
	const typeKinds = grammarRoles.get('type');
	const builtinKinds = new Set(grammarRoles.get('type.builtin'));
	const filteredKinds = typeKinds.filter((k) => !builtinKinds.has(k));

	const resolveNode = (k: string) => nodeMap.nodes.get(k) ?? nodeMap.nodes.get(`_${k}`);
	const typeIdKind = filteredKinds.find((k) => k !== 'identifier' && resolveNode(k) !== undefined);
	if (!typeIdKind) {
		const identKind = filteredKinds.find((k) => k === 'identifier' && resolveNode(k) !== undefined);
		if (identKind) {
			const node = resolveNode(identKind)!;
			if (isLeafFactory(node)) {
				fns.push(`  type(name: string): ${returnTypeExpr(node)} {`);
				fns.push(`    return F.${node.rawFactoryName}(name);`);
				fns.push('  },');
			}
		}
		return;
	}

	const typeNode = resolveNode(typeIdKind)!;

	if (isLeafFactory(typeNode)) {
		fns.push(`  type(name: string): ${returnTypeExpr(typeNode)} {`);
		fns.push(`    return F.${typeNode.rawFactoryName}(name);`);
		fns.push('  },');
	} else {
		const identNode = nodeMap.nodes.get('identifier');
		if (identNode && isLeafFactory(identNode)) {
			fns.push(`  type(name: string): ${returnTypeExpr(typeNode)} {`);
			fns.push(`    return F.${typeNode.rawFactoryName}(F.${identNode.rawFactoryName}(name));`);
			fns.push('  },');
		}
	}
}

function emitSynonymIdentifier(grammarRoles: GrammarRoles, nodeMap: NodeMap, fns: string[]): void {
	const varKinds = grammarRoles.get('variable');

	const identKind = varKinds.find((k) => k === 'identifier');
	if (!identKind) return;

	const node = nodeMap.nodes.get(identKind);
	if (!node || !isLeafFactory(node)) return;

	fns.push(`  identifier(name: string): ${returnTypeExpr(node)} {`);
	fns.push(`    return F.${node.rawFactoryName}(name);`);
	fns.push('  },');
}

function emitSynonymAliases(grammarRoles: GrammarRoles, nodeMap: NodeMap, fns: string[]): void {
	const ALIAS_ROLES: readonly { role: Role; canonicalName: string }[] = [
		{ role: 'definition.function', canonicalName: 'function' },
		{ role: 'definition.class', canonicalName: 'class' },
		{ role: 'definition.method', canonicalName: 'method' },
		{ role: 'definition.module', canonicalName: 'module' },
		{ role: 'definition.interface', canonicalName: 'interface' }
	];

	for (const { role, canonicalName } of ALIAS_ROLES) {
		const kinds = grammarRoles.get(role);
		if (kinds.length === 0) continue;
		const primaryKind = kinds[0]!;
		const node = nodeMap.nodes.get(primaryKind);
		if (!node?.rawFactoryName) continue;
		const irKey = node.irKey ?? memberKeyFor(primaryKind, '');
		fns.push(`  // ${role} → ${primaryKind}`);
		fns.push(`  get ${canonicalName}(): (typeof ir)['${irKey}'] { return ir.${irKey}; },`);
	}
}
